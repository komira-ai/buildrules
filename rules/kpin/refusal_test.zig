//! What kpin says when its inputs are wrong, as a person is shown it: `main.run` over real files in a scratch directory, the exit status and the whole `error:` /
//! `ALARM:` line on stderr, and nothing written. The cases in pins_test.zig, toml_test.zig, npm_test.zig and lockfmt_test.zig call the parsers and read that a
//! problem was found (and most of them a word of it); main_test.zig reads exit statuses. These are the sentences of the command: they name the file, the table and the
//! line, and say what to run or to write instead.
//!
//! The first case is the control: inputs that are right are accepted, so a kpin that refuses everything is red.

const std = @import("std");
const fetch = @import("fetch.zig");
const fx = @import("fixtures.zig");
const main = @import("main.zig");
const t = std.testing;

const Run = struct { code: u8, out: []const u8, err: []const u8 };

const Env = struct {
    ar: std.heap.ArenaAllocator,
    tmp: std.testing.TmpDir,
    dir: []const u8,
    http: fetch.HttpFetcher,

    fn init() !*Env {
        const e = try t.allocator.create(Env);
        e.ar = std.heap.ArenaAllocator.init(t.allocator);
        e.tmp = std.testing.tmpDir(.{});
        e.dir = try e.tmp.dir.realpathAlloc(e.ar.allocator(), ".");
        e.http = .{ .allocator = e.ar.allocator() };
        return e;
    }

    fn deinit(e: *Env) void {
        e.tmp.cleanup();
        e.ar.deinit();
        t.allocator.destroy(e);
    }

    fn a(e: *Env) std.mem.Allocator {
        return e.ar.allocator();
    }

    fn write(e: *Env, name: []const u8, data: []const u8) void {
        e.tmp.dir.writeFile(.{ .sub_path = name, .data = data }) catch @panic("write");
    }

    fn exists(e: *Env, name: []const u8) bool {
        e.tmp.dir.access(name, .{}) catch return false;
        return true;
    }

    /// `kpin <cmd> --pins pins.toml --lock pins.lock.bzl [--npm package-lock.json]` in the scratch directory, then `extra`.
    fn kpin(e: *Env, cmd: []const u8, with_npm: bool, extra: []const []const u8) Run {
        var argv = std.ArrayList([]const u8).empty;
        argv.append(e.a(), cmd) catch @panic("oom");
        for ([_][]const u8{ "pins.toml", "pins.lock.bzl" }, [_][]const u8{ "--pins", "--lock" }) |f, flag| {
            argv.append(e.a(), flag) catch @panic("oom");
            argv.append(e.a(), std.fmt.allocPrint(e.a(), "{s}/{s}", .{ e.dir, f }) catch @panic("oom")) catch @panic("oom");
        }
        if (with_npm) argv.appendSlice(e.a(), &.{ "--npm", std.fmt.allocPrint(e.a(), "{s}/package-lock.json", .{e.dir}) catch @panic("oom") }) catch @panic("oom");
        argv.appendSlice(e.a(), extra) catch @panic("oom");
        var out = std.Io.Writer.Allocating.init(e.a());
        var err = std.Io.Writer.Allocating.init(e.a());
        const code = main.run(e.a(), argv.items, &out.writer, &err.writer, &e.http);
        return .{ .code = code, .out = out.written(), .err = err.written() };
    }

    /// The command `cmd` refuses with `code`, `msgs` all on stderr, nothing on stdout, and no lock written.
    fn refuses(e: *Env, name: []const u8, r: Run, code: u8, msgs: []const []const u8) !void {
        var ok = r.code == code and r.out.len == 0 and !e.exists("pins.lock.bzl.kpin-tmp");
        for (msgs) |m| ok = ok and std.mem.indexOf(u8, r.err, m) != null;
        if (!ok) {
            std.debug.print("{s}: exit {d} (want {d}), stdout:\n{s}\nstderr:\n{s}\nwanted on stderr:\n", .{ name, r.code, code, r.out, r.err });
            for (msgs) |m| std.debug.print("  {s}\n", .{m});
            return error.TestUnexpectedResult;
        }
    }
};

const TOOL = "[tool]\nversion = \"1.0.0\"\nurl = \"https://h.example/tool-{version}.bin\"\n";
const ABC = fx.ABC_SHA256;
const ABD_SHA = "0ec1dc2fd2ab3a2ba9c5c1ad1fcd7b6c1e0f3c4fe0d2c6f0b8fd1d9a9d3f2a10";

/// A lock holding `tool` 1.0.0 for `any`, with the sha256 and size of "abc".
const LOCK =
    \\# GENERATED by kpin.
    \\
    \\KPIN_LOCK_VERSION = 1
    \\
    \\PINS = {
    \\    "tool": {
    \\        "version": "1.0.0",
    \\        "files": {
    \\            "any": {
    \\                "url": "https://h.example/tool-1.0.0.bin",
    \\                "sha256": "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
    \\                "size": 3,
    \\            },
    \\        },
    \\    },
    \\}
    \\
    \\NPM = {}
    \\
;

test "inputs that are right are accepted: a pin with its hash, and the lock that says so" {
    const e = try Env.init();
    defer e.deinit();
    e.write("pins.toml", TOOL ++ "[tool.platform.any]\nsha256 = \"" ++ ABC ++ "\"\nsize = 3\n");
    const r = e.kpin("lock", false, &.{});
    try t.expectEqual(@as(u8, 0), r.code);
    try t.expect(e.exists("pins.lock.bzl"));
    try t.expectEqual(@as(u8, 0), e.kpin("check", false, &.{}).code);
}

