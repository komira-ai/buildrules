test "a lock that is stale is refused with the command to run, and a hash that changed is an alarm that regenerating would hide" {
    {
        const e = try Env.init();
        defer e.deinit();
        e.write("pins.toml", TOOL ++ "[tool.platform.any]\nsha256 = \"" ++ ABC ++ "\"\nsize = 3\n");
        e.write("pins.lock.bzl", "KPIN_LOCK_VERSION = 1\n\nPINS = {}\n\nNPM = {}\n");
        try e.refuses("a lock without the pin", e.kpin("check", false, &.{}), 1, &.{ "pins.lock.bzl is stale: it is not what the inputs produce. Run `./buck2 run buildrules//rules/kpin -- lock` (or `update`) and commit the result" });
    }
    {
        // The lock says the bytes of tool 1.0.0 are those of "abc"; pins.toml now claims other bytes for the same version.
        const e = try Env.init();
        defer e.deinit();
        e.write("pins.toml", TOOL ++ "[tool.platform.any]\nsha256 = \"" ++ ABD_SHA ++ "\"\nsize = 3\n");
        e.write("pins.lock.bzl", LOCK);
        const alarm = "ALARM: tool 1.0.0 (any): pins.toml says sha256 " ++ ABD_SHA ++ " size 3, the lock has " ++ ABC ++ " size 3";
        const why = "ALARM: a hash changed for a version that is already locked. Regenerating would hide it; read the project's announcement, and if the change is legitimate a human accepts it in review.";
        try e.refuses("pins.toml contradicts the lock (check)", e.kpin("check", false, &.{}), 3, &.{ alarm, why });
        try e.refuses("pins.toml contradicts the lock (lock)", e.kpin("lock", false, &.{}), 3, &.{ alarm, why });
        // an alarm is not fixed by regenerating: the lock is the one it was
        try t.expectEqualStrings(LOCK, try e.tmp.dir.readFileAlloc(e.a(), "pins.lock.bzl", 1 << 16));
    }
    {
        // The registry's integrity for a locked package changed under the same version.
        const e = try Env.init();
        defer e.deinit();
        const sri_b = try fx.sri512(e.a(), "abd");
        e.write("pins.toml", TOOL ++ "[tool.platform.any]\nsha256 = \"" ++ ABC ++ "\"\nsize = 3\n");
        e.write("package-lock.json", try fx.packageLock(e.a(), &.{.{ .path = "node_modules/left-pad", .version = "1.3.0", .resolved = "https://registry.example/left-pad.tgz", .integrity = sri_b }}));
        const lock = try std.fmt.allocPrint(e.a(), "{s}", .{std.mem.trimRight(u8, LOCK, "\n")});
        const with_npm = try std.mem.replaceOwned(u8, e.a(), lock, "NPM = {}", try std.fmt.allocPrint(e.a(),
            \\NPM = {{
            \\    "left-pad@1.3.0": {{
            \\        "name": "left-pad",
            \\        "version": "1.3.0",
            \\        "url": "https://registry.example/left-pad.tgz",
            \\        "sri512": "{s}",
            \\        "sha256": "{s}",
            \\        "size": 3,
            \\    }},
            \\}}
        , .{ fx.ABC_SRI512, ABC }));
        e.write("pins.lock.bzl", try std.fmt.allocPrint(e.a(), "{s}\n", .{with_npm}));
        try e.refuses("package-lock.json has other bytes for a locked version", e.kpin("check", true, &.{}), 3, &.{ "ALARM: left-pad@1.3.0: package-lock.json says integrity ", ": same version, different bytes", "ALARM: a hash changed for a version that is already locked" });
    }
}

test "a bad command line is a usage error that says which part, and prints the usage" {
    const e = try Env.init();
    defer e.deinit();
    const usage = "usage: kpin <command> [flags]";
    const cases = [_]struct { name: []const u8, argv: []const []const u8, msg: []const u8 }{
        .{ .name = "no command", .argv = &.{}, .msg = "kpin: NoCommand" },
        .{ .name = "a command that is not one", .argv = &.{"frobnicate"}, .msg = "kpin: UnknownCommand" },
        .{ .name = "a flag that is not one", .argv = &.{ "lock", "--bogus" }, .msg = "kpin: UnknownFlag" },
        .{ .name = "a flag with no value", .argv = &.{ "lock", "--pins" }, .msg = "kpin: MissingValue" },
        .{ .name = "an update flag on lock", .argv = &.{ "lock", "--verify" }, .msg = "kpin: WrongCommand" },
        .{ .name = "a check flag on update", .argv = &.{ "update", "--previous", "base.bzl" }, .msg = "kpin: WrongCommand" },
        .{ .name = "a size that is not a number", .argv = &.{ "update", "--max-bytes", "lots" }, .msg = "kpin: BadNumber" },
    };
    for (cases) |c| {
        var out = std.Io.Writer.Allocating.init(e.a());
        var err = std.Io.Writer.Allocating.init(e.a());
        const code = main.run(e.a(), c.argv, &out.writer, &err.writer, &e.http);
        if (code != 2 or out.written().len != 0 or std.mem.indexOf(u8, err.written(), c.msg) == null or std.mem.indexOf(u8, err.written(), usage) == null) {
            std.debug.print("{s}: exit {d}, stderr:\n{s}\n", .{ c.name, code, err.written() });
            return error.TestUnexpectedResult;
        }
    }
}
