//! The small readers of the files a sync leaves or reads back: Cargo.lock (cargo_lock.zig), the generated table (lockfile.zig), rust-toolchain.toml
//! (toolchain.zig) and the root Cargo.toml's workspace (workspace.zig). A reader that accepts what it should refuse makes `check` green on a stale
//! repository, so each refusal is named by the text it refuses and the message it must give.

const std = @import("std");
const cargo_lock = @import("cargo_lock.zig");
const contract = @import("contract.zig");
const Diag = @import("diag.zig").Diag;
const kit = @import("testkit.zig");
const lockfile = @import("lockfile.zig");
const toolchain = @import("toolchain.zig");
const ws = @import("workspace.zig");
const t = std.testing;

const h64 = "0123456789abcdef" ** 4;
const h64b = "fedcba9876543210" ** 4;

fn hasMsg(d: *const Diag, needle: []const u8) bool {
    for (d.msgs.items) |m| if (std.mem.indexOf(u8, m, needle) != null) return true;
    return false;
}

fn expectMsg(d: *const Diag, needle: []const u8) !void {
    if (hasMsg(d, needle)) return;
    std.debug.print("no message holds `{s}`; got {d}:\n", .{ needle, d.count() });
    for (d.msgs.items) |m| std.debug.print("  {s}\n", .{m});
    return error.TestExpectedMessage;
}

// ---- cargo_lock.zig ------------------------------------------------------------------------------------------

const lock_ok =
    "# This file is automatically @generated by Cargo.\n" ++
    "version = 4\n\n" ++
    "[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"itoa\",\n \"serde\",\n]\n\n" ++
    "[[package]]\nname = \"itoa\"\nversion = \"1.0.15\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n" ++
    "checksum = \"" ++ h64 ++ "\"\ndependencies = [\"x\"]\n";

fn lockOf(a: std.mem.Allocator, text: []const u8, d: *Diag) ![]cargo_lock.Entry {
    return cargo_lock.parse(a, "Cargo.lock", text, d);
}

test "cargo_lock: the packages, their sources and checksums in file order; dependency lists are skipped" {
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    var d = Diag.init(ar.allocator());
    const es = try lockOf(ar.allocator(), lock_ok, &d);
    try t.expectEqual(@as(usize, 2), es.len);
    try t.expectEqualStrings("app", es[0].name);
    try t.expectEqualStrings("0.1.0", es[0].version);
    try t.expectEqualStrings("", es[0].source);
    try t.expectEqualStrings("itoa", es[1].name);
    try t.expectEqualStrings("registry+https://github.com/rust-lang/crates.io-index", es[1].source);
    try t.expectEqualStrings(h64, es[1].checksum);
    try t.expectEqual(@as(usize, 0), d.count());
}

test "cargo_lock: a [metadata] table and lines before the packages are not packages; CRLF and blank lines are read" {
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    var d = Diag.init(ar.allocator());
    const es = try lockOf(ar.allocator(), "version = 3\r\nsomething = 1\r\n\r\n[[package]]\r\nname = \"a\"\r\nversion = \"1.0.0\"\r\n\r\n[metadata]\r\n\"checksum a 1.0.0 (registry+x)\" = \"abc\"\r\n", &d);
    try t.expectEqual(@as(usize, 1), es.len);
    try t.expectEqualStrings("a", es[0].name);
    // A package with `name =` that is not quoted properly keeps the empty name and is refused below.
    var d2 = Diag.init(ar.allocator());
    try t.expectError(error.Invalid, lockOf(ar.allocator(), "version = 4\n[[package]]\nname = \"\nversion = \"1.0.0\"\n", &d2));
    try expectMsg(&d2, "without a name or a version");
    var d3 = Diag.init(ar.allocator());
    try t.expectError(error.Invalid, lockOf(ar.allocator(), "version = 4\n[[package]]\nname = a\nversion = \"1.0.0\"\n", &d3));
    try expectMsg(&d3, "without a name or a version");
}

test "cargo_lock: every refusal gives its message and the whole read fails" {
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    const cases = [_]struct { text: []const u8, needle: []const u8 }{
        .{ .text = "[[package]]\nname = \"a\"\nversion = \"1.0.0\"\n", .needle = "no `version = N` line" },
        .{ .text = "version = x\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\n", .needle = "no `version = N` line" },
        .{ .text = "version = 2\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\n", .needle = "lock version 2 is not 3 or 4" },
        .{ .text = "version = 5\n", .needle = "lock version 5 is not 3 or 4" },
        .{ .text = "version = 4\n[[package]]\nname = \"a\\\\b\"\nversion = \"1.0.0\"\n", .needle = "Cargo.lock:3: a backslash in a value" },
        .{ .text = "version = 4\n[[package]]\nversion = \"1.0.0\"\n", .needle = "without a name or a version" },
        .{ .text = "version = 4\n[[package]]\nname = \"a\"\n", .needle = "without a name or a version" },
        .{ .text = "version = 4\n[[package]]\nname = \"bad name\"\nversion = \"1.0.0\"\n", .needle = "unsupported characters" },
        .{ .text = "version = 4\n[[package]]\nname = \"a\"\nversion = \"-1\"\n", .needle = "unsupported characters" },
        .{ .text = "version = 4\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\n[[package]]\nname = \"b$\"\nversion = \"1.0.0\"\n", .needle = "package `b$`" },
    };
    for (cases) |c| {
        var d = Diag.init(a);
        if (lockOf(a, c.text, &d)) |_| {
            std.debug.print("accepted: {s}\n", .{c.text});
            return error.AcceptedABadLock;
        } else |err| try t.expectEqual(error.Invalid, err);
        try expectMsg(&d, c.needle);
        try kit.sweepRefusalLast(cargo_lock.parse, .{ "Cargo.lock", c.text });
    }
}

const LockCall = struct {
    pub fn call(_: @This(), a: std.mem.Allocator) !bool {
        var d = Diag.init(a);
        const es = try lockOf(a, lock_ok, &d);
        return es.len == 2;
    }
};

test "cargo_lock: out of memory ends the read with an error, never with a short list" {
    try kit.sweepOom(LockCall{}, true);
}

// ---- lockfile.zig --------------------------------------------------------------------------------------------

const table_ok = std.fmt.comptimePrint(
    "# generated\nSCHEMA = {d}\nRUSTC = \"1.95.0\"\nTARGET = \"{s}\"\nCARGO_LOCK_SHA256 = \"{s}\"\nMANIFEST_SHA256 = {{\n" ++
        "    \"Cargo.toml\": \"{s}\",\n    \"crates/hello/Cargo.toml\": \"{s}\",\n}}\nUNITS = {{}}\n",
    .{ contract.schema, contract.target, h64, h64, h64b },
);

test "lockfile: the keys check needs, the manifests in order, and the hash recorded for a path" {
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    var d = Diag.init(ar.allocator());
    const lk = try lockfile.parse(ar.allocator(), "t.bzl", table_ok, &d);
    try t.expectEqual(contract.schema, lk.schema);
    try t.expectEqualStrings("1.95.0", lk.rustc);
    try t.expectEqualStrings(contract.target, lk.target);
    try t.expectEqualStrings(h64, lk.lock_sha256);
    try t.expectEqual(@as(usize, 2), lk.manifests.len);
    try t.expectEqualStrings("crates/hello/Cargo.toml", lk.manifests[1].path);
    try t.expectEqualStrings(h64b, lockfile.manifestHash(lk, "crates/hello/Cargo.toml").?);
    try t.expectEqualStrings(h64, lockfile.manifestHash(lk, "Cargo.toml").?);
    try t.expect(lockfile.manifestHash(lk, "other/Cargo.toml") == null);
}

fn tableWith(a: std.mem.Allocator, from: []const u8, to: []const u8) ![]u8 {
    return std.mem.replaceOwned(u8, a, table_ok, from, to);
}

test "lockfile: every missing or malformed line is a message and the read fails" {
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    const cases = [_]struct { from: []const u8, to: []const u8, needle: []const u8 }{
        .{ .from = "SCHEMA = 2\n", .to = "", .needle = "no `SCHEMA = N` line" },
        .{ .from = "SCHEMA = 2\n", .to = "SCHEMA = x\n", .needle = "`SCHEMA = x` is not a number" },
        .{ .from = "SCHEMA = 2\n", .to = "SCHEMA = 1\n", .needle = "SCHEMA = 1, but this buildrules reads schema 2" },
        .{ .from = "RUSTC = \"1.95.0\"\n", .to = "", .needle = "no RUSTC line" },
        .{ .from = "RUSTC = \"1.95.0\"\n", .to = "RUSTC = 1.95.0\n", .needle = "no RUSTC line" },
        .{ .from = "TARGET = \"x86_64-unknown-linux-gnu\"\n", .to = "", .needle = "no TARGET line" },
        .{ .from = "CARGO_LOCK_SHA256 = \"" ++ h64 ++ "\"\n", .to = "", .needle = "no valid CARGO_LOCK_SHA256 line" },
        .{ .from = "CARGO_LOCK_SHA256 = \"" ++ h64 ++ "\"\n", .to = "CARGO_LOCK_SHA256 = \"zz\"\n", .needle = "no valid CARGO_LOCK_SHA256 line" },
        .{ .from = "MANIFEST_SHA256 = {\n    \"Cargo.toml\": \"" ++ h64 ++ "\",\n    \"crates/hello/Cargo.toml\": \"" ++ h64b ++ "\",\n}\n", .to = "", .needle = "no MANIFEST_SHA256 block" },
        .{ .from = "MANIFEST_SHA256 = {\n", .to = "MANIFEST_SHA256 = {\"Cargo.toml\": \"x\"}\nIGNORED = {\n", .needle = "one entry per line" },
        .{ .from = "}\nUNITS", .to = "UNITS", .needle = "block is not closed" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    not a line\n", .needle = "a MANIFEST_SHA256 line is not" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    \"Cargo.toml\": \"" ++ h64 ++ "\"\n", .needle = "a MANIFEST_SHA256 line is not" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    Cargo.toml\": \"" ++ h64 ++ "\",\n", .needle = "a MANIFEST_SHA256 line is not" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    \"Cargo.toml\" \"" ++ h64 ++ "\",\n", .needle = "a MANIFEST_SHA256 line is not" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    \"p\": \"x,\n", .needle = "a MANIFEST_SHA256 line is not" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    \"p\": \"xyz,\n", .needle = "a MANIFEST_SHA256 line is not" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    \"p\",\n", .needle = "a MANIFEST_SHA256 line is not" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    \"../Cargo.toml\": \"" ++ h64 ++ "\",\n", .needle = "entry `../Cargo.toml` has a bad path or hash" },
        .{ .from = "    \"Cargo.toml\": \"" ++ h64 ++ "\",\n", .to = "    \"Cargo.toml\": \"zz\",\n", .needle = "entry `Cargo.toml` has a bad path or hash" },
    };
    for (cases) |c| {
        var d = Diag.init(a);
        const text = try tableWith(a, c.from, c.to);
        try t.expect(!std.mem.eql(u8, text, table_ok));
        if (lockfile.parse(a, "t.bzl", text, &d)) |_| {
            std.debug.print("accepted a table without: {s}\n", .{c.needle});
            return error.AcceptedABadTable;
        } else |err| try t.expectEqual(error.Invalid, err);
        try expectMsg(&d, c.needle);
        // Not swept for a failing allocation: lockfile.parse trusts `diag.count()` after its checks, and `Diag.add` drops a message it cannot allocate,
        // so under memory exhaustion it unwraps a key it found missing (lockfile.zig, the final return) and the process aborts. Reported, not pinned.
    }
}

test "lockfile: stringLine is exactly `KEY = \"value\"`; firstDifference counts lines from 1" {
    try t.expectEqualStrings("x", lockfile.stringLine("RUSTC = \"x\"", "RUSTC").?);
    try t.expectEqualStrings("", lockfile.stringLine("RUSTC = \"\"", "RUSTC").?);
    try t.expect(lockfile.stringLine("RUSTC = x", "RUSTC") == null);
    try t.expect(lockfile.stringLine("RUSTC = \"x", "RUSTC") == null);
    try t.expect(lockfile.stringLine("RUSTC = \"", "RUSTC") == null);
    try t.expect(lockfile.stringLine("RUSTCX = \"x\"", "RUSTC") == null);
    try t.expect(lockfile.stringLine("TARGET = \"x\"", "RUSTC") == null);
    try t.expect(lockfile.stringLine("", "RUSTC") == null);
    try t.expectEqual(@as(usize, 1), lockfile.firstDifference("a\nb\n", "x\nb\n"));
    try t.expectEqual(@as(usize, 3), lockfile.firstDifference("a\nb\nc\n", "a\nb\nd\n"));
    // One text is the start of the other: the difference is at the line the shorter one ends on.
    try t.expectEqual(@as(usize, 2), lockfile.firstDifference("a\n", "a\nb\n"));
    try t.expectEqual(@as(usize, 2), lockfile.firstDifference("a\nb\n", "a\n"));
}

const TableCall = struct {
