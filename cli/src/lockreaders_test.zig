// ---- toolchain.zig -------------------------------------------------------------------------------------------

test "toolchain: the channel line, in the forms people write it, and what is not a channel" {
    try t.expectEqualStrings("1.95.0", toolchain.channel("[toolchain]\nchannel = \"1.95.0\"\n").?);
    try t.expectEqualStrings("1.95.0", toolchain.channel("channel=\"1.95.0\"").?);
    try t.expectEqualStrings("1.95.0", toolchain.channel("  channel \t= \t \"1.95.0\" \r\n").?);
    try t.expectEqualStrings("", toolchain.channel("channel = \"\"").?);
    // `channels = ...` is another key; the real one after it is found.
    try t.expectEqualStrings("1.1.1", toolchain.channel("channels = 1\nchannel = \"1.1.1\"\n").?);
    try t.expect(toolchain.channel("channel\n") == null);
    try t.expect(toolchain.channel("channel = stable\n") == null);
    try t.expect(toolchain.channel("channel = \"open\n") == null);
    try t.expect(toolchain.channel("channel = \n") == null);
    try t.expect(toolchain.channel("channel = \"") == null);
    try t.expect(toolchain.channel("components = []\n") == null);
    try t.expect(toolchain.channel("") == null);
}

test "toolchain: only N.N.N with at most four digits a part is an exact release" {
    try t.expect(toolchain.isExactRelease("1.95.0"));
    try t.expect(toolchain.isExactRelease("0.0.0"));
    try t.expect(toolchain.isExactRelease("1234.5678.9012"));
    try t.expect(!toolchain.isExactRelease("12345.0.0"));
    try t.expect(!toolchain.isExactRelease("1.95"));
    try t.expect(!toolchain.isExactRelease("1.95.0.1"));
    try t.expect(!toolchain.isExactRelease("1..0"));
    try t.expect(!toolchain.isExactRelease(".1.0"));
    try t.expect(!toolchain.isExactRelease("1.0."));
    try t.expect(!toolchain.isExactRelease("1.x.0"));
    try t.expect(!toolchain.isExactRelease("1.0.0-beta"));
    try t.expect(!toolchain.isExactRelease("1.0./"));
    try t.expect(!toolchain.isExactRelease("stable"));
    try t.expect(!toolchain.isExactRelease(""));
}

test "toolchain: judge gives the pin, or the message for a missing file, a missing channel, a floating channel and a path" {
    try t.expectEqualStrings("1.95.0", toolchain.judge("[toolchain]\nchannel = \"1.95.0\"\ncomponents = []\npathological = 1\n").ok);
    try t.expect(std.mem.indexOf(u8, toolchain.judge(null).bad, "is missing") != null);
    try t.expect(std.mem.indexOf(u8, toolchain.judge("[toolchain]\n").bad, "no `channel") != null);
    try t.expect(std.mem.indexOf(u8, toolchain.judge("channel = \"stable\"\n").bad, "not an exact release") != null);
    try t.expect(std.mem.indexOf(u8, toolchain.judge("channel = \"1.95.0\"\npath = \"/opt/rust\"\n").bad, "`path` names a toolchain") != null);
    try t.expect(std.mem.indexOf(u8, toolchain.judge("channel = \"1.95.0\"\n path=\"/opt/rust\"\n").bad, "`path` names a toolchain") != null);
    try t.expectEqualStrings("1.95.0", toolchain.judge("channel = \"1.95.0\"\npath\n").ok);
    try t.expectEqualStrings("1.95.0", toolchain.judge("channel = \"1.95.0\"\npath : x\n").ok);
}

