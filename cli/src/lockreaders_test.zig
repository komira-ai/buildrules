test "workspace: the [workspace] body ends at the next table, at the end of the text, or is absent" {
    const text = "[package]\nname = \"x\"\n[workspace]\nmembers = [\"a\"]\n[profile.release]\nlto = true\n";
    const s = ws.workspaceSection(text).?;
    try t.expectEqualStrings("members = [\"a\"]\n", text[s.start..s.end]);
    const to_end = "[workspace]\nmembers = []";
    const e = ws.workspaceSection(to_end).?;
    try t.expectEqualStrings("members = []", to_end[e.start..e.end]);
    const crlf = ws.workspaceSection("  [workspace]  \r\nmembers = []\r\n").?;
    try t.expectEqual(@as(usize, 17), crlf.start);
    try t.expect(ws.workspaceSection("[package]\nname = \"x\"\n") == null);
    try t.expect(ws.workspaceSection("") == null);
    // The header with nothing after it.
    const bare = ws.workspaceSection("[workspace]").?;
    try t.expectEqual(bare.start, bare.end);
    try t.expect(ws.isPackage("x = 1\n  [package]  \r\n"));
    try t.expect(!ws.isPackage("[workspace]\n"));
    try t.expect(!ws.hasLine("", "[package]"));
}

test "workspace: member patterns are the quoted strings of `members`, comments skipped, other keys ignored" {
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    const got = try ws.memberPatterns(a, "[workspace]\nexclude = [\"nope\"]\nmembership = 1\nmembers = [\n  \"a\", # \"commented\"\n  \"b/*\",\n]\nresolver = \"2\"\n");
    try t.expectEqual(@as(usize, 2), got.len);
    try t.expectEqualStrings("a", got[0]);
    try t.expectEqualStrings("b/*", got[1]);
    try t.expectEqual(@as(usize, 1), (try ws.memberPatterns(a, "[workspace]\nmembers=[\"only\"]")).len);
    // No [workspace]; no `members`; `members` that is not a list; a list that is never closed.
    try t.expectEqual(@as(usize, 0), (try ws.memberPatterns(a, "[package]\nmembers = [\"x\"]\n")).len);
    try t.expectEqual(@as(usize, 0), (try ws.memberPatterns(a, "[workspace]\nresolver = \"2\"\n")).len);
    try t.expectEqual(@as(usize, 0), (try ws.memberPatterns(a, "[workspace]\nmembers = \"x\"\n")).len);
    try t.expectEqual(@as(usize, 0), (try ws.memberPatterns(a, "[workspace]\nmembers")).len);
    try t.expectEqual(@as(usize, 1), (try ws.memberPatterns(a, "[workspace]\nmembers = [\"x\"")).len);
    try t.expectEqual(@as(usize, 0), (try ws.memberPatterns(a, "[workspace]\nmembers = [\"x")).len);
}

fn member(h: *kit.Harness, dir: []const u8) !void {
    const path = try std.fmt.allocPrint(h.a(), "{s}/Cargo.toml", .{dir});
    try h.put(path, "[package]\nname = \"m\"\n");
}

test "workspace: member directories are the listed ones that have a Cargo.toml and the subdirectories of `dir/*` that do, sorted; other globs are refused" {
    const h = try kit.Harness.create();
    defer h.destroy();
    try member(h, "crates/b");
    try member(h, "crates/a");
    try member(h, "tools/x");
    try h.put("crates/not_a_dir", "a file, not a directory\n");
    try h.put("crates/empty/README", "no manifest\n");
    const got = try ws.memberDirs(&h.ctx, "[workspace]\nmembers = [\"tools/x\", \"crates/*\", \"missing/dir\", \"gone/*\"]\n");
    try t.expectEqual(@as(usize, 3), got.len);
    try t.expectEqualStrings("crates/a", got[0]);
    try t.expectEqualStrings("crates/b", got[1]);
    try t.expectEqualStrings("tools/x", got[2]);
    for ([_][]const u8{ "crates/*/x", "*", "a?b", "[ab]", "crates/*x", "c*/*" }) |pat| {
        const doc = try std.fmt.allocPrint(h.a(), "[workspace]\nmembers = [\"{s}\"]\n", .{pat});
        try t.expectError(error.UnsupportedMemberPattern, ws.memberDirs(&h.ctx, doc));
    }
}
