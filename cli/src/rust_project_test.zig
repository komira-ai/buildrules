test "one crate per compiled unit the index names: a build-script run is not a crate, the script it runs is" {
    const h = try fresh();
    defer h.destroy();
    const p = try developed(h);
    // 10 units in the index, one of them a run; the script the run runs is a crate (its build.rs), and it is there once.
    try t.expectEqual(@as(usize, 9), val.items(val.get(p, "crates")).len);
    var scripts: usize = 0;
    for (val.items(val.get(p, "crates"))) |c| {
        if (std.mem.endsWith(u8, val.getStr(c, "root_module").?, "build.rs")) scripts += 1;
    }
    try t.expectEqual(@as(usize, 1), scripts);
    try t.expectEqualStrings("build-script-build", val.getStr(row(p, "crates/app/build.rs", ""), "display_name").?);
}

test "a crate's dependencies are the rows of its table dependencies, by extern name; a build-script run, a binary and a repeated edge are not" {
    const h = try fresh();
    defer h.destroy();
    const p = try developed(h);
    try t.expectEqualStrings("mac=mac reg=reg drp=drp ", try depNames(h.a(), p, row(p, "crates/app/src/lib.rs", "feature=\"fast\"")));
    try t.expectEqualStrings("mac=mac ", try depNames(h.a(), p, row(p, "crates/app/src/lib.rs", "test")));
    try t.expectEqualStrings("app=app ", try depNames(h.a(), p, row(p, "crates/app/tests/it.rs", "")));
    try t.expectEqualStrings("rpm=rpm ", try depNames(h.a(), p, row(p, "crates/reg-1.0.0-rc.1+meta/src/lib.rs", "")));
}

test "the crate graph has no cycles and every edge names a row" {
    const h = try fresh();
    defer h.destroy();
    const p = try developed(h);
    const crates = val.items(val.get(p, "crates"));
    // Depth-first from every row; a row met again on the current path is a cycle.
    const state = try h.a().alloc(u8, crates.len);
    @memset(state, 0);
    const Walk = struct {
        fn visit(cs: []const Value, st: []u8, i: usize) !void {
            if (st[i] == 2) return;
            if (st[i] == 1) return error.Cycle;
            st[i] = 1;
            for (val.items(val.get(cs[i], "deps"))) |d| {
                const n: usize = @intCast(val.get(d, "crate").?.integer);
                try t.expect(n < cs.len);
                try visit(cs, st, n);
            }
            st[i] = 2;
        }
    };
    for (0..crates.len) |i| try Walk.visit(crates, state, i);
}

test "a build script's OUT_DIR, --cfg and rustc-env reach every crate compiled with its run, with the run's path tokens made paths" {
    const h = try fresh();
    defer h.destroy();
    const p = try developed(h);
    const a = h.a();
    const inputs = try std.fs.path.join(a, &.{ root(h), "ra" });
    const out_dir = try std.fs.path.join(a, &.{ inputs, "build/app-0.1.0_run0000000/OUT_DIR" });
    const manifest = try std.fs.path.join(a, &.{ root(h), "crates/app" });
    for ([_][]const u8{ "feature=\"fast\"", "test" }) |which| {
        const c = row(p, "crates/app/src/lib.rs", which);
        const env = val.get(c, "env").?;
        try t.expectEqualStrings(out_dir, val.getStr(env, "OUT_DIR").?);
        try t.expectEqualStrings(try std.fmt.allocPrint(a, "{s}/gen.rs", .{out_dir}), val.getStr(env, "GEN_FILE").?);
        try t.expectEqualStrings("abc=def", val.getStr(env, "STAMP").?);
        try t.expect(hasStr(val.get(c, "cfg"), "has_gen"));
        try t.expect(hasStr(val.get(c, "cfg"), try std.fmt.allocPrint(a, "where=\"{s}\"", .{manifest})));
        // --check-cfg, -l: not cfgs
        try t.expect(!hasStr(val.get(c, "cfg"), "cfg(has_gen)") and !hasStr(val.get(c, "cfg"), "static=foo"));
        // rust-analyzer finds an included file only in the crate's own source root
        const inc = val.get(val.get(c, "source").?, "include_dirs").?;
        try t.expect(hasStr(inc, manifest) and hasStr(inc, out_dir));
    }
    // A member's directories outside its package (`extra_srcs`) are its own too, for every crate of the member.
    for ([_][]const u8{ "crates/app/build.rs", "crates/app/tests/it.rs" }) |m| {
        const inc = val.get(val.get(row(p, m, ""), "source").?, "include_dirs").?;
        try t.expect(hasStr(inc, try std.fs.path.join(a, &.{ root(h), "shared" })) and hasStr(inc, try std.fs.path.join(a, &.{ root(h), "shared/more" })));
    }
    // A crate without a build script has no OUT_DIR, and only its own directory.
    const m = row(p, "crates/mac/src/lib.rs", "");
    try t.expect(val.get(val.get(m, "env").?, "OUT_DIR") == null);
    try t.expectEqual(@as(usize, 1), val.items(val.get(val.get(m, "source").?, "include_dirs")).len);
}

