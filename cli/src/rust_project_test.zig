fn refusedWith(h: *kit.Harness, argv: []const []const u8, want: []const u8) !void {
    const r = h.run(argv);
    if (r.code != 1 or !kit.contains(r.err, want)) {
        std.debug.print("want exit 1 and `{s}`, got {d}: {s}\n", .{ want, r.code, r.err });
        return error.TestUnexpectedResult;
    }
    try t.expect(!h.has("rust-project.json"));
}

