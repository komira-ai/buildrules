test "usage: a verb is required and known, flags take values, a flag of the other verb is refused, check takes one target" {
    const h = try fresh();
    defer h.destroy();
    const cases = [_]struct { argv: []const []const u8, want: []const u8 }{
        .{ .argv = &.{"rust-project"}, .want = "rust-project: develop or check?" },
        .{ .argv = &.{ "rust-project", "build" }, .want = "rust-project: unknown command build" },
        .{ .argv = &.{ "rust-project", "develop", "--dir" }, .want = "rust-project develop: --dir needs a value" },
        .{ .argv = &.{ "rust-project", "develop", "--project" }, .want = "rust-project develop: --project needs a value" },
        .{ .argv = &.{ "rust-project", "develop", "//x:flycheck" }, .want = "rust-project develop: unknown argument //x:flycheck" },
        .{ .argv = &.{ "rust-project", "check", "--inputs", "ra", "//x:flycheck" }, .want = "rust-project check: unknown argument --inputs" },
        .{ .argv = &.{ "rust-project", "check" }, .want = "rust-project check: which target?" },
        .{ .argv = &.{ "rust-project", "check", "//a:flycheck", "//b:flycheck" }, .want = "rust-project check: unknown argument //b:flycheck" },
        .{ .argv = &.{ "rust-project", "check", "crates/app/src/lib.rs" }, .want = "rust-project check: crates/app/src/lib.rs is not a target (//<member>:flycheck)" },
        .{ .argv = &.{ "rust-project", "check", "//crates/app" }, .want = "is not a target" },
    };
    for (cases) |c| {
        const r = h.run(c.argv);
        if (r.code != 2 or !kit.contains(r.err, c.want)) {
            std.debug.print("want exit 2 and `{s}`, got {d}: {s}\n", .{ c.want, r.code, r.err });
            return error.TestUnexpectedResult;
        }
    }
    try t.expectEqual(@as(usize, 0), n_calls);
}

