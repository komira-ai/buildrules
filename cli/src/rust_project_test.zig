/// The inputs directory at `dir`.
fn putInputs(h: *kit.Harness, comptime dir: []const u8, idx: []const u8) !void {
    try h.put(dir ++ "/index.json", idx);
    // One argument per line, a `--cfg` followed by its value; the tokens a run records in place of the worker's paths.
    try h.put(dir ++ "/build/app-0.1.0_run0000000/rustc_args", "--cfg\nhas_gen\n--check-cfg\ncfg(has_gen)\n-l\nstatic=foo\n--cfg\nwhere=\"{MANIFEST_DIR}\"\n");
    try h.put(dir ++ "/build/app-0.1.0_run0000000/rustc_env", "GEN_FILE={OUT_DIR}/gen.rs\n\nSTAMP=abc=def\n");
    try h.put(dir ++ "/build/app-0.1.0_run0000000/OUT_DIR/gen.rs", "pub fn generated() {}\n");
    try h.put(dir ++ "/build/reg-1.0.0_run0000000/rustc_args", "");
    try h.put(dir ++ "/build/reg-1.0.0_run0000000/rustc_env", "");
    try h.put(dir ++ "/crates/reg-1.0.0-rc.1+meta/src/lib.rs", "");
    try h.put(dir ++ "/crates/rpm-1.0.0/src/lib.rs", "");
    try h.put(dir ++ "/crates/drp-2.0.0/src/lib.rs", "");
    try h.put(dir ++ "/proc-macro/mac-0.1.0_pm00000000/libmac.so", "");
    try h.put(dir ++ "/proc-macro/rpm-1.0.0_pm00000000/librpm.so", "");
    try h.put(dir ++ "/sysroot/bin/rustc", "");
    // A standard library without std_detect: a crate the release does not have is left out, with the edges to it.
    for ([_][]const u8{ "core", "alloc", "std", "proc_macro", "test" }) |c| {
        try h.put(try std.fmt.allocPrint(h.a(), dir ++ "/rust-src/library/{s}/src/lib.rs", .{c}), "");
    }
}

var calls: [16][]const u8 = undefined;
var n_calls: usize = 0;
var buck2_build_code: u8 = 0;
var buck2_root_code: u8 = 0;
var buck2_root_out: []const u8 = "/proj\n";
var exec_error: ?anyerror = null;
/// An error from the exec seam for `buck2 root` only (the build ran).
var root_exec_error: ?anyerror = null;
/// What the fake `buck2 build //x:flycheck --out DIR` writes into DIR: file name -> lines.
var flycheck_files: []const [2][]const u8 = &.{};

fn fakeExec(ctx: *ctxm.Ctx, spec: ctxm.Exec) anyerror!ctxm.ExecResult {
    if (!kit.replaying) {
        calls[n_calls] = try std.mem.join(ctx.a, " ", spec.argv);
        n_calls += 1;
    }
    if (exec_error) |e| return e;
    if (spec.argv.len >= 2 and std.mem.eql(u8, spec.argv[1], "root")) {
        if (root_exec_error) |e| return e;
        return .{ .code = buck2_root_code, .stdout = buck2_root_out };
    }
    if (buck2_build_code != 0) return .{ .code = buck2_build_code };
    // `build TARGET --out DIR`: the output lands in DIR.
    const out = spec.argv[spec.argv.len - 1];
    if (std.mem.endsWith(u8, spec.argv[2], ":rust_analyzer_inputs")) {
        try putInputsCtx(ctx, out);
    } else {
        for (flycheck_files) |f| try ctx.write(try std.fmt.allocPrint(ctx.a, "{s}/{s}", .{ out, f[0] }), f[1]);
    }
    return .{ .code = 0 };
}

/// putInputs through the context (the fake buck2 writes into the directory the command runs in, also during a replay).
fn putInputsCtx(ctx: *ctxm.Ctx, dir: []const u8) !void {
    const files = [_][2][]const u8{
        .{ "index.json", index_all },
        .{ "build/app-0.1.0_run0000000/rustc_args", "--cfg\nhas_gen\n" },
        .{ "build/app-0.1.0_run0000000/rustc_env", "" },
        .{ "build/reg-1.0.0_run0000000/rustc_args", "" },
        .{ "build/reg-1.0.0_run0000000/rustc_env", "" },
        .{ "rust-src/library/core/src/lib.rs", "" },
    };
    for (files) |f| try ctx.write(try std.fmt.allocPrint(ctx.a, "{s}/{s}", .{ dir, f[0] }), f[1]);
}

fn fresh() !*kit.Harness {
    const h = try kit.Harness.create();
    h.ctx.execer = &fakeExec;
    n_calls = 0;
    buck2_build_code = 0;
    buck2_root_code = 0;
    buck2_root_out = "/proj\n";
    exec_error = null;
    root_exec_error = null;
    flycheck_files = &.{};
    try h.put("buildrules.lock.bzl", table);
    try h.put("third_party/buildrules/overrides.json", overrides);
    return h;
}

/// `develop --inputs ra` on the fixture, and the file it wrote.
fn developed(h: *kit.Harness) !Value {
    try putInputs(h, "ra", index_all);
    const r = h.run(&.{ "rust-project", "develop", "--inputs", "ra" });
    if (r.code != 0) std.debug.panic("develop failed: {s}", .{r.err});
    return std.json.parseFromSliceLeaky(Value, h.a(), h.read("rust-project.json"), .{});
}

fn root(h: *kit.Harness) []const u8 {
    return h.ctx.dir.realpathAlloc(h.a(), ".") catch unreachable;
}

/// The row of the crate whose root module ends with `module` and whose cfgs include `cfg` (empty: any).
fn row(p: Value, module: []const u8, cfg: []const u8) Value {
    for (val.items(val.get(p, "crates"))) |c| {
        if (!std.mem.endsWith(u8, val.getStr(c, "root_module").?, module)) continue;
        if (cfg.len == 0 or hasStr(val.get(c, "cfg"), cfg)) return c;
    }
    std.debug.panic("no crate {s} {s}", .{ module, cfg });
}

fn hasStr(v: ?Value, s: []const u8) bool {
    for (val.items(v)) |x| if (x == .string and std.mem.eql(u8, x.string, s)) return true;
    return false;
}

fn depNames(a: std.mem.Allocator, p: Value, c: Value) ![]const u8 {
    var o = std.ArrayList(u8).empty;
    const crates = val.items(val.get(p, "crates"));
    for (val.items(val.get(c, "deps"))) |d| {
        const target = crates[@intCast(val.get(d, "crate").?.integer)];
        try o.print(a, "{s}={s} ", .{ val.getStr(d, "name").?, val.getStr(target, "display_name").? });
    }
    return o.items;
}

