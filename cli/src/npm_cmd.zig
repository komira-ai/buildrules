//! `buildrules npm sync|check`: an npm package's files in, the generated table out (docs/contract.md,
//! "npm"). package.json and package-lock.json are read here, because Starlark cannot read JSON; the
//! table (buildrules.lock.bzl) and the glue (buildrules.bzl) are what the `npm_package` macro
//! (rules/node/npm.bzl) reads. `sync` is the only command that touches the network, and only to pin
//! a tarball the table does not hold yet (its sha256 and size are what Buck2 keys the download on);
//! `check` is offline and read-only.

const std = @import("std");
const ctxm = @import("ctx.zig");
const fetch = @import("fetch.zig");
const valid = @import("valid.zig");
const Diag = @import("diag.zig").Diag;
const Ctx = ctxm.Ctx;

/// `SCHEMA` of the table; rules/node/npm.bzl refuses any other.
pub const schema: u32 = 1;
/// The node the rules pin (rules/node/pins.bzl NODE.version); the macro refuses a table made for another.
pub const node_version = "24.21.0";
pub const lock_file = "buildrules.lock.bzl";
pub const bzl_file = "buildrules.bzl";
pub const steps = [_][]const u8{ "typecheck", "lint", "test", "build" };

pub const usage_text =
    \\usage: buildrules npm sync  [PATH...] [--dir DIR] [--seed FILE] [--accept-changed] [--check]
    \\       buildrules npm check [PATH...] [--dir DIR]
    \\
    \\  PATH...   package directories (each holds package.json and package-lock.json), relative to --dir;
    \\            none = every directory under --dir that has a buildrules.lock.bzl written by this command
    \\  --dir DIR the repository root (default .)
    \\  --seed FILE   sync: a table or a kpin pins.lock.bzl whose sha256 and size are reused for the same
    \\            package at the same sha512 integrity (so migrating needs no download)
    \\  --accept-changed   sync: allow a package version whose integrity differs from the table's (the
    \\            registry or the lockfile now says other bytes: read why before using this)
    \\  --check   sync: write nothing, exit 1 unless sync would change nothing (same as `npm check`)
    \\
    \\sync writes buildrules.lock.bzl and buildrules.bzl next to package.json, and a BUCK file with
    \\`npm_package(path = ".")` if the directory has none. A tarball not in the table (or the seed) is
    \\downloaded once to learn its sha256 and size, and its sha512 must be the lockfile's.
    \\Exit codes: 0 ok, 1 failed, refused or stale, 2 usage.
    \\
;

