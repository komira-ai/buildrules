/// The network seam: the sha256, sha512 and size of the body at `url`. Tests replace it.
pub const Fetch = *const fn (a: std.mem.Allocator, url: []const u8) anyerror!fetch.Digest.Result;
pub var fetcher: Fetch = &httpDigest;

fn httpDigest(a: std.mem.Allocator, url: []const u8) anyerror!fetch.Digest.Result {
    var http = fetch.HttpFetcher{ .allocator = a };
    var d = fetch.Digest{ .max = 1 << 30 };
    try http.fetcher().get(url, d.sink());
    return d.finish(a);
}

const Opts = struct {
    dir: []const u8 = ".",
    paths: []const []const u8 = &.{},
    seed: ?[]const u8 = null,
    accept_changed: bool = false,
    check: bool = false,
};

pub fn run(root: *Ctx, args: []const []const u8) u8 {
    if (args.len == 0) return root.usage("npm: a subcommand is needed\n{s}", .{usage_text});
    const sub = args[0];
    const is_sync = std.mem.eql(u8, sub, "sync");
    if (!is_sync and !std.mem.eql(u8, sub, "check")) return root.usage("npm: unknown subcommand {s}\n{s}", .{ sub, usage_text });
    var o = Opts{};
    var paths = std.ArrayList([]const u8).empty;
    var i: usize = 1;
    while (i < args.len) : (i += 1) {
        const arg = args[i];
        if (std.mem.eql(u8, arg, "--dir") or (is_sync and std.mem.eql(u8, arg, "--seed"))) {
            const v = ctxm.flagValue(args, &i) orelse return root.usage("npm {s}: {s} needs a value", .{ sub, arg });
            if (std.mem.eql(u8, arg, "--dir")) o.dir = v else o.seed = v;
        } else if (is_sync and std.mem.eql(u8, arg, "--accept-changed")) {
            o.accept_changed = true;
        } else if (is_sync and std.mem.eql(u8, arg, "--check")) {
            o.check = true;
        } else if (std.mem.startsWith(u8, arg, "-")) {
            return root.usage("npm {s}: unknown argument {s}\n{s}", .{ sub, arg, usage_text });
        } else {
            paths.append(root.a, arg) catch return root.fail("out of memory", .{});
        }
    }
    if (!is_sync) o.check = true;
    o.paths = paths.items;
    var ctx = root.into(o.dir) catch |e| return root.fail("cannot open {s}: {s}", .{ o.dir, @errorName(e) });
    defer ctx.dir.close();
    return runIn(&ctx, o) catch |e| root.fail("npm {s}: {s}", .{ sub, @errorName(e) });
}

fn runIn(ctx: *Ctx, o: Opts) !u8 {
    var dirs = std.ArrayList([]const u8).empty;
    if (o.paths.len > 0) {
        for (o.paths) |p| try dirs.append(ctx.a, std.mem.trimRight(u8, p, "/"));
    } else {
        try findTables(ctx, ".", &dirs, 0);
        if (dirs.items.len == 0) return ctx.fail("no package under {s} has a {s}; name the directories to sync", .{ o.dir, lock_file });
    }
    var seed: ?[]const u8 = null;
    if (o.seed) |s| seed = ctx.read(s) catch |e| return ctx.fail("cannot read --seed {s}: {s}", .{ s, @errorName(e) });
    var bad: usize = 0;
    for (dirs.items) |d| {
        var diag = Diag.init(ctx.a);
        const changed = onePackage(ctx, d, o, seed, &diag) catch |e| blk: {
            diag.add("{s}", .{@errorName(e)});
            break :blk false;
        };
        for (diag.msgs.items) |m| _ = ctx.fail("{s}: {s}", .{ d, m });
        if (diag.lost > 0) _ = ctx.fail("{s}: {s}", .{ d, Diag.lost_text });
        if (diag.count() > 0) {
            bad += 1;
        } else if (o.check) {
            if (changed) bad += 1 else ctx.say("{s}: in sync", .{d});
        }
    }
    if (bad > 0 and o.check) _ = ctx.fail("{d} package(s) stale or refused; run `buildrules npm sync` and commit the result", .{bad});
    return if (bad == 0) ctxm.exit_ok else ctxm.exit_fail;
}

/// Directories (below `rel`, to depth 8, never node_modules, buck-out or dot-directories) with a table
/// this command wrote.
fn findTables(ctx: *Ctx, rel: []const u8, out: *std.ArrayList([]const u8), depth: u8) !void {
    if (depth > 8) return;
    var d = try ctx.dir.openDir(rel, .{ .iterate = true });
    defer d.close();
    var it = d.iterate();
    var subs = std.ArrayList([]const u8).empty;
    var has_table = false;
    while (try it.next()) |e| {
        if (e.kind == .file and std.mem.eql(u8, e.name, lock_file)) {
            const text = d.readFileAlloc(ctx.a, lock_file, 64 << 20) catch continue;
            if (std.mem.indexOf(u8, text, "buildrules npm sync") != null) has_table = true;
        } else if (e.kind == .directory and e.name[0] != '.' and !std.mem.eql(u8, e.name, "node_modules") and !std.mem.eql(u8, e.name, "buck-out")) {
            try subs.append(ctx.a, try ctx.a.dupe(u8, e.name));
        }
    }
    if (has_table) try out.append(ctx.a, if (std.mem.eql(u8, rel, ".")) "." else rel);
    std.mem.sort([]const u8, subs.items, {}, lessStr);
    for (subs.items) |s| try findTables(ctx, if (std.mem.eql(u8, rel, ".")) s else try std.fs.path.join(ctx.a, &.{ rel, s }), out, depth + 1);
}

fn lessStr(_: void, x: []const u8, y: []const u8) bool {
    return std.mem.lessThan(u8, x, y);
}

// ---- reading the package -------------------------------------------------------------------

pub const Pin = struct {
    key: []const u8,
    name: []const u8,
    version: []const u8,
    url: []const u8,
    sri512: []const u8,
    sha256: ?[]const u8 = null,
    size: ?u64 = null,
    os: ?[]const []const u8 = null,
    cpu: ?[]const []const u8 = null,
    libc: ?[]const []const u8 = null,
};

fn objStr(o: std.json.ObjectMap, key: []const u8) ?[]const u8 {
    const v = o.get(key) orelse return null;
    return if (v == .string) v.string else null;
}

fn objFlag(o: std.json.ObjectMap, key: []const u8) bool {
    const v = o.get(key) orelse return false;
    return v == .bool and v.bool;
}

pub fn strList(a: std.mem.Allocator, o: std.json.ObjectMap, key: []const u8, diag: *Diag, where: []const u8) ?[]const []const u8 {
    const v = o.get(key) orelse return null;
    if (v != .array) {
        diag.add("{s}: {s} is not an array", .{ where, key });
        return null;
    }
    var out = std.ArrayList([]const u8).empty;
    for (v.array.items) |x| {
        if (x != .string or x.string.len == 0 or x.string.len > 32 or !valid.isToken(if (x.string[0] == '!') x.string[1..] else x.string)) {
            diag.add("{s}: {s} holds a value this tool does not accept", .{ where, key });
            return null;
        }
        out.append(a, x.string) catch return null;
    }
    if (out.items.len == 0) return null;
    return out.items;
}

/// The packages of package-lock.json (lockfileVersion 3) that have a tarball, sorted by key, each once.
fn readLock(a: std.mem.Allocator, text: []const u8, diag: *Diag) ![]Pin {
    const parsed = std.json.parseFromSlice(std.json.Value, a, text, .{}) catch {
        diag.add("package-lock.json is not valid JSON", .{});
        return &.{};
    };
    if (parsed.value != .object) {
        diag.add("package-lock.json is not a JSON object", .{});
        return &.{};
    }
    const root = parsed.value.object;
    const lv = root.get("lockfileVersion");
    if (lv == null or lv.? != .integer or lv.?.integer != 3) {
        diag.add("package-lock.json is not lockfileVersion 3 (run npm >= 9 with --lockfile-version=3)", .{});
        return &.{};
    }
    const pk = root.get("packages") orelse {
        diag.add("package-lock.json has no `packages` object", .{});
        return &.{};
    };
    if (pk != .object) {
        diag.add("package-lock.json `packages` is not an object", .{});
        return &.{};
    }
    const marker = "node_modules/";
    var list = std.ArrayList(Pin).empty;
    for (pk.object.keys(), pk.object.values()) |path, e| {
        if (path.len == 0) continue;
        if (e != .object) {
            diag.add("packages[{s}] is not an object", .{path});
            continue;
        }
        const o = e.object;
        if (objFlag(o, "link") or objFlag(o, "inBundle")) continue;
        const at = std.mem.lastIndexOf(u8, path, marker);
        if (objStr(o, "resolved") == null and at == null) continue; // a workspace member
        const resolved = objStr(o, "resolved") orelse {
            diag.add("packages[{s}] has no `resolved` (a git or file dependency); it cannot be pinned", .{path});
            continue;
        };
        const integrity = objStr(o, "integrity") orelse {
            diag.add("packages[{s}] has no `integrity`", .{path});
            continue;
        };
        const name = objStr(o, "name") orelse if (at) |i| path[i + marker.len ..] else {
            diag.add("packages[{s}] has no name", .{path});
            continue;
        };
        const version = objStr(o, "version") orelse {
            diag.add("packages[{s}] has no version", .{path});
            continue;
        };
        if (!std.mem.startsWith(u8, integrity, "sha512-") or !valid.isSri512(integrity)) {
            diag.add("packages[{s}] integrity is not a sha512 of 64 bytes (sha1 and sha256 integrities are refused)", .{path});
            continue;
        }
        if (!std.mem.startsWith(u8, resolved, "https://") or !valid.isUrl(resolved)) {
            diag.add("packages[{s}] resolved is not an https URL this tool accepts", .{path});
            continue;
        }
        if (!valid.isPackageName(name) or !valid.isVersion(version)) {
            diag.add("packages[{s}] has a name or version with unsupported characters", .{path});
            continue;
        }
        const where = try std.fmt.allocPrint(a, "packages[{s}]", .{path});
        try list.append(a, .{
            .key = try std.fmt.allocPrint(a, "{s}@{s}", .{ name, version }),
            .name = name,
            .version = version,
            .url = resolved,
            .sri512 = integrity,
            .os = strList(a, o, "os", diag, where),
            .cpu = strList(a, o, "cpu", diag, where),
            .libc = strList(a, o, "libc", diag, where),
        });
    }
    std.mem.sort(Pin, list.items, {}, lessPin);
    var out = std.ArrayList(Pin).empty;
    for (list.items) |p| {
        if (out.items.len > 0 and std.mem.eql(u8, out.items[out.items.len - 1].key, p.key)) {
            if (!std.mem.eql(u8, out.items[out.items.len - 1].sri512, p.sri512))
                diag.add("{s} appears twice with different integrities", .{p.key});
            continue;
        }
        try out.append(a, p);
    }
    return out.items;
}

fn lessPin(_: void, x: Pin, y: Pin) bool {
    return std.mem.lessThan(u8, x.key, y.key);
}

/// The policy and scripts of package.json, validated, as the table's text and the facts the table needs.
pub const Manifest = struct { name: ?[]const u8, version: ?[]const u8, scripts: []const [2][]const u8, policy: std.json.ObjectMap };

pub fn readManifest(a: std.mem.Allocator, text: []const u8, diag: *Diag) !?Manifest {
    const parsed = std.json.parseFromSlice(std.json.Value, a, text, .{}) catch {
        diag.add("package.json is not valid JSON", .{});
        return null;
    };
    if (parsed.value != .object) {
        diag.add("package.json is not a JSON object", .{});
        return null;
    }
    const root = parsed.value.object;
    if (root.get("workspaces") != null) diag.add("package.json has \"workspaces\": npm workspaces are not supported yet (one npm_package per package.json; this is a recorded gap in docs/contract.md)", .{});
    var scripts = std.ArrayList([2][]const u8).empty;
    if (root.get("scripts")) |sv| {
        if (sv != .object) {
            diag.add("package.json \"scripts\" is not an object", .{});
        } else for (sv.object.keys(), sv.object.values()) |k, v| {
            if (v != .string) {
                diag.add("package.json script {s} is not a string", .{k});
                continue;
            }
            try scripts.append(a, .{ k, v.string });
        }
    }
    std.mem.sort([2][]const u8, scripts.items, {}, lessPair);
    var policy = std.json.ObjectMap.init(a);
    if (root.get("buildrules")) |pv| {
        if (pv != .object) {
            diag.add("package.json \"buildrules\" is not an object", .{});
        } else policy = pv.object;
    }
    try checkPolicy(a, policy, scripts.items, diag);
    return .{ .name = objStr(root, "name"), .version = objStr(root, "version"), .scripts = scripts.items, .policy = policy };
}

fn lessPair(_: void, x: [2][]const u8, y: [2][]const u8) bool {
    return std.mem.lessThan(u8, x[0], y[0]);
}

fn hasScript(scripts: []const [2][]const u8, name: []const u8) bool {
    for (scripts) |s| if (std.mem.eql(u8, s[0], name)) return true;
    return false;
}

fn isStep(s: []const u8) bool {
    for (steps) |x| if (std.mem.eql(u8, x, s)) return true;
    return false;
}

fn checkPolicy(a: std.mem.Allocator, policy: std.json.ObjectMap, scripts: []const [2][]const u8, diag: *Diag) !void {
    for (policy.keys(), policy.values()) |k, v| {
        if (std.mem.eql(u8, k, "dist")) {
            if (v != .string or !valid.isRelPath(v.string)) diag.add("buildrules.dist must be a relative directory (no `..`, no leading or trailing `/`)", .{});
        } else if (std.mem.eql(u8, k, "default-action")) {
            if (v != .string) diag.add("buildrules.default-action must be a string", .{});
        } else if (std.mem.eql(u8, k, "steps")) {
            if (v != .object) {
                diag.add("buildrules.steps must be an object of step -> script name", .{});
                continue;
            }
            for (v.object.keys(), v.object.values()) |sk, sv| {
                if (!isStep(sk)) diag.add("buildrules.steps.{s}: not a step ({s}, {s}, {s}, {s})", .{ sk, steps[0], steps[1], steps[2], steps[3] });
                if (sv != .string) {
                    diag.add("buildrules.steps.{s} must be a script name", .{sk});
                } else if (!hasScript(scripts, sv.string)) {
                    diag.add("buildrules.steps.{s} names the script {s}, which package.json lacks", .{ sk, sv.string });
                }
            }
        } else if (std.mem.eql(u8, k, "actions")) {
            if (v != .object) {
                diag.add("buildrules.actions must be an object of action -> list of steps", .{});
                continue;
            }
            for (v.object.keys(), v.object.values()) |ak, av| {
                if (isStep(ak) or std.mem.eql(u8, ak, "dist") or std.mem.eql(u8, ak, "check") or std.mem.eql(u8, ak, "node_modules") or !valid.isPinName(ak))
                    diag.add("buildrules.actions.{s}: the name is a step's or a target's, or not a lower-case name", .{ak});
                if (av != .array or av.array.items.len == 0) {
                    diag.add("buildrules.actions.{s} must be a non-empty list of steps", .{ak});
                    continue;
                }
                for (av.array.items) |x| {
                    if (x != .string or !isStep(x.string)) diag.add("buildrules.actions.{s} names something that is not a step", .{ak});
                }
            }
        } else {
            diag.add("package.json \"buildrules\" has the key {s}; allowed: steps, actions, dist, default-action", .{k});
        }
    }
    _ = a;
}

// ---- the previous table, and a kpin lock -----------------------------------------------------

const Known = struct { sri512: []const u8, sha256: []const u8, size: u64 };

fn quoted(line: []const u8) ?[]const u8 {
    if (line.len < 2 or line[0] != '"') return null;
    const end = std.mem.indexOfScalarPos(u8, line, 1, '"') orelse return null;
    return line[1..end];
}

/// {key: sri512, sha256, size} of the `NPM = {` block of a table or a kpin lock: the generated layout, one
/// field per line. Anything that is not that layout yields no entry (the package is then fetched).
fn readKnown(a: std.mem.Allocator, text: []const u8) !std.StringHashMap(Known) {
    var m = std.StringHashMap(Known).init(a);
    var in_npm = false;
    var key: ?[]const u8 = null;
    var sri: ?[]const u8 = null;
    var sha: ?[]const u8 = null;
    var size: ?u64 = null;
    var it = std.mem.splitScalar(u8, text, '\n');
    while (it.next()) |line| {
        if (!in_npm) {
            if (std.mem.eql(u8, line, "NPM = {")) in_npm = true;
            continue;
        }
        if (std.mem.eql(u8, line, "}")) break;
        if (std.mem.startsWith(u8, line, "    \"") and std.mem.endsWith(u8, line, "\": {")) {
            key = quoted(line[4..]);
            sri = null;
            sha = null;
            size = null;
        } else if (std.mem.eql(u8, line, "    },")) {
            if (key != null and sri != null and sha != null and size != null and valid.isSha256(sha.?))
                try m.put(key.?, .{ .sri512 = sri.?, .sha256 = sha.?, .size = size.? });
            key = null;
        } else if (std.mem.startsWith(u8, line, "        \"sri512\": ")) {
            sri = quoted(line["        \"sri512\": ".len..]);
        } else if (std.mem.startsWith(u8, line, "        \"sha256\": ")) {
            sha = quoted(line["        \"sha256\": ".len..]);
        } else if (std.mem.startsWith(u8, line, "        \"size\": ")) {
            const v = std.mem.trimRight(u8, line["        \"size\": ".len..], ",");
            size = std.fmt.parseInt(u64, v, 10) catch null;
        }
    }
    return m;
}

// ---- rendering --------------------------------------------------------------------------------

fn writeStr(w: anytype, s: []const u8) !void {
    try w.writeByte('"');
    for (s) |c| switch (c) {
        '"' => try w.writeAll("\\\""),
        '\\' => try w.writeAll("\\\\"),
        '\n' => try w.writeAll("\\n"),
        '\r' => try w.writeAll("\\r"),
        '\t' => try w.writeAll("\\t"),
        0...8, 11, 12, 14...31, 127 => try w.print("\\x{x:0>2}", .{c}),
        else => try w.writeByte(c),
    };
    try w.writeByte('"');
}

fn writeList(w: anytype, items: []const []const u8) !void {
    try w.writeByte('[');
    for (items, 0..) |s, i| {
        if (i > 0) try w.writeAll(", ");
        try writeStr(w, s);
    }
    try w.writeByte(']');
}

fn sortedKeys(a: std.mem.Allocator, o: std.json.ObjectMap) ![]const []const u8 {
    const ks = try a.dupe([]const u8, o.keys());
    std.mem.sort([]const u8, ks, {}, lessStr);
    return ks;
}

pub fn render(a: std.mem.Allocator, m: Manifest, pj_sha: []const u8, lock_sha: []const u8, pins: []const Pin) ![]u8 {
    var buf = std.ArrayList(u8).empty;
    const w = buf.writer(a);
    try w.writeAll("# GENERATED by `buildrules npm sync`. Do not edit by hand: `buildrules npm check` fails on a changed file.\n");
    try w.writeAll("# Read by buildrules.bzl and rules/node/npm.bzl (docs/contract.md, \"npm\").\n\n");
    try w.print("SCHEMA = {d}\nNODE = \"{s}\"\nPACKAGE_JSON_SHA256 = \"{s}\"\nPACKAGE_LOCK_SHA256 = \"{s}\"\n\nPACKAGE = {{\n", .{ schema, node_version, pj_sha, lock_sha });
    if (m.name) |n| {
        try w.writeAll("    \"name\": ");
        try writeStr(w, n);
        try w.writeAll(",\n");
    }
    if (m.version) |n| {
        try w.writeAll("    \"version\": ");
        try writeStr(w, n);
        try w.writeAll(",\n");
    }
    try w.writeAll("    \"scripts\": {\n");
    for (m.scripts) |s| {
        try w.writeAll("        ");
        try writeStr(w, s[0]);
        try w.writeAll(": ");
        try writeStr(w, s[1]);
        try w.writeAll(",\n");
    }
    try w.writeAll("    },\n    \"buildrules\": {\n");
    for (try sortedKeys(a, m.policy)) |k| {
        const v = m.policy.get(k).?;
        try w.writeAll("        ");
        try writeStr(w, k);
        try w.writeAll(": ");
        if (v == .string) {
            try writeStr(w, v.string);
            try w.writeAll(",\n");
        } else {
            try w.writeAll("{\n");
            for (try sortedKeys(a, v.object)) |k2| {
                const v2 = v.object.get(k2).?;
                try w.writeAll("            ");
                try writeStr(w, k2);
                try w.writeAll(": ");
                if (v2 == .string) {
                    try writeStr(w, v2.string);
                } else {
                    var l = std.ArrayList([]const u8).empty;
                    for (v2.array.items) |x| try l.append(a, x.string);
                    try writeList(w, l.items);
                }
                try w.writeAll(",\n");
            }
            try w.writeAll("        },\n");
        }
    }
    try w.writeAll("    },\n}\n\nNPM = {\n");
    for (pins) |p| {
        try w.writeAll("    ");
        try writeStr(w, p.key);
        try w.writeAll(": {\n");
        const fields = [_][2][]const u8{ .{ "name", p.name }, .{ "version", p.version }, .{ "url", p.url }, .{ "sri512", p.sri512 }, .{ "sha256", p.sha256.? } };
        for (fields) |f| {
            try w.print("        \"{s}\": ", .{f[0]});
            try writeStr(w, f[1]);
            try w.writeAll(",\n");
        }
        try w.print("        \"size\": {d},\n", .{p.size.?});
        const lists = [_]struct { n: []const u8, v: ?[]const []const u8 }{ .{ .n = "os", .v = p.os }, .{ .n = "cpu", .v = p.cpu }, .{ .n = "libc", .v = p.libc } };
        for (lists) |l| if (l.v) |items| {
            try w.print("        \"{s}\": ", .{l.n});
            try writeList(w, items);
            try w.writeAll(",\n");
        };
        try w.writeAll("    },\n");
    }
    try w.writeAll("}\n");
    return buf.items;
}

// ---- one package -------------------------------------------------------------------------------

fn join(a: std.mem.Allocator, dir: []const u8, name: []const u8) ![]u8 {
    if (std.mem.eql(u8, dir, ".")) return a.dupe(u8, name);
    return std.fs.path.join(a, &.{ dir, name });
}

fn differs(ctx: *Ctx, path: []const u8, want: []const u8) !bool {
    const have = try ctx.readOpt(path) orelse return true;
    return !std.mem.eql(u8, have, want);
}

/// Syncs or checks one package directory. Returns whether any file differs from (check) or was changed by
/// (sync) what is on disk; problems go to `diag`.
fn onePackage(ctx: *Ctx, dir: []const u8, o: Opts, seed: ?[]const u8, diag: *Diag) !bool {
    const a = ctx.a;
    const table_path = try join(a, dir, lock_file);
    const built = (try buildTable(ctx, dir, o.check, o.accept_changed, seed, diag)) orelse return false;
    const table = built.table;
    const bzl_path = try join(a, dir, bzl_file);
    const buck_path = try join(a, dir, "BUCK");

    var changed = false;
    if (try differs(ctx, table_path, table)) {
        changed = true;
        if (o.check) diag.add("{s} is stale: it is not what package.json and package-lock.json produce", .{lock_file}) else {
            try ctx.write(table_path, table);
            ctx.say("{s}: wrote {s} ({d} packages)", .{ dir, lock_file, built.packages });
        }
    }
    if (try differs(ctx, bzl_path, bzl_text)) {
        changed = true;
        if (o.check) diag.add("{s} is not what sync writes (hand-edited, or from another version)", .{bzl_file}) else {
            try ctx.write(bzl_path, bzl_text);
            ctx.say("{s}: wrote {s}", .{ dir, bzl_file });
        }
    }
    const buck = try ctx.readOpt(buck_path);
    if (buck == null) {
        changed = true;
        if (o.check) diag.add("no BUCK file with an npm_package call", .{}) else {
            try ctx.write(buck_path, buck_text);
            ctx.say("{s}: wrote BUCK", .{dir});
        }
    } else if (std.mem.indexOf(u8, buck.?, "npm_package(") == null) {
        diag.add("the BUCK file has no npm_package call (add `load(\":{s}\", \"npm_package\")` and `npm_package(path = \".\")`)", .{bzl_file});
    }
    return changed;
}

pub const Built = struct { table: []u8, packages: usize };

/// The text `sync` writes as `buildrules.lock.bzl` of the package directory `dir`, from its package.json and
/// package-lock.json, the table already there and `seed`: a tarball that neither holds is downloaded once (never
/// when `check_only`). Nothing is written. Null, with the reasons in `diag`, when the table cannot be made.
pub fn buildTable(ctx: *Ctx, dir: []const u8, check_only: bool, accept_changed: bool, seed: ?[]const u8, diag: *Diag) !?Built {
    const a = ctx.a;
    const pj_path = try join(a, dir, "package.json");
    const lk_path = try join(a, dir, "package-lock.json");
    const pj_text = try ctx.readOpt(pj_path) orelse {
        diag.add("no package.json", .{});
        return null;
    };
    const lk_text = try ctx.readOpt(lk_path) orelse {
        diag.add("no package-lock.json (run `npm install --package-lock-only --lockfile-version=3`)", .{});
        return null;
    };
    const man = try readManifest(a, pj_text, diag);
    const found = try readLock(a, lk_text, diag);
    if (diag.count() > 0 or man == null) return null;

    const table_path = try join(a, dir, lock_file);
    const prev_text = try ctx.readOpt(table_path);
    const known = try readKnown(a, prev_text orelse "");
    const seeded = try readKnown(a, seed orelse "");

    var pins = std.ArrayList(Pin).empty;
    for (found) |p0| {
        var p = p0;
        if (known.get(p.key)) |k| {
            if (std.mem.eql(u8, k.sri512, p.sri512)) {
                p.sha256 = k.sha256;
                p.size = k.size;
            } else if (!accept_changed) {
                diag.add("{s}: package-lock.json says {s} but the table pins {s}: the same version with other bytes (a republished package, or a tampered lockfile); read why, then sync with --accept-changed", .{ p.key, p.sri512, k.sri512 });
                continue;
            }
        }
        if (p.sha256 == null) if (seeded.get(p.key)) |k| if (std.mem.eql(u8, k.sri512, p.sri512)) {
            p.sha256 = k.sha256;
            p.size = k.size;
        };
        if (p.sha256 == null) {
            if (check_only) {
                diag.add("{s} is in package-lock.json and not in the table: run `buildrules npm sync`", .{p.key});
                continue;
            }
            const d = fetcher(a, p.url) catch |e| {
                diag.add("{s}: fetching {s}: {s}", .{ p.key, p.url, @errorName(e) });
                continue;
            };
            if (!std.mem.eql(u8, d.sri512, p.sri512)) {
                diag.add("{s}: the bytes at {s} have sha512 {s}; package-lock.json says {s}. Nothing was pinned", .{ p.key, p.url, d.sri512, p.sri512 });
                continue;
            }
            p.sha256 = d.sha256;
            p.size = d.size;
            ctx.say("{s}: pinned {s} ({d} bytes)", .{ dir, p.key, d.size });
        }
        try pins.append(a, p);
    }
    if (diag.count() > 0) return null;

    const pj_sha = try ctxm.sha256Hex(a, pj_text);
    const lk_sha = try ctxm.sha256Hex(a, lk_text);
    return .{ .table = try render(a, man.?, pj_sha, lk_sha, pins.items), .packages = pins.items.len };
}
