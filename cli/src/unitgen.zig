const Pkg = struct { name: []const u8, ver: []const u8, registry: bool, rel: ?[]const u8, root_file: []const u8, dir: []const u8 };

const Gen = struct {
    a: std.mem.Allocator,
    d: *Diag,
    root: []const u8, // with a trailing slash
    lock: std.StringHashMap(cargo_lock.Entry),
    links: std.StringHashMap(?[]const u8),

    fn packageLinks(g: *Gen, dir: []const u8) Error!?[]const u8 {
        if (g.links.get(dir)) |l| return l;
        const path = try std.fmt.allocPrint(g.a, "{s}/Cargo.toml", .{std.mem.trimRight(u8, dir, "/")});
        const text = std.fs.cwd().readFileAlloc(g.a, path, 8 << 20) catch |e| return die(g.d, "cannot read the manifest of {s}: {s}", .{ dir, @errorName(e) });
        const doc = toml.parse(g.a, text);
        if (doc.msg.len != 0) return die(g.d, "{s}:{d}: {s}", .{ path, doc.line, doc.msg });
        const l = val.asStr(toml.at(doc.value, &.{ "package", "links" }));
        try g.links.put(dir, l);
        return l;
    }

    fn pkgOf(g: *Gen, u: Value) Error!Pkg {
        const pid = val.getStr(u, "pkg_id") orelse return die(g.d, "a unit has no pkg_id", .{});
        const target = val.get(u, "target") orelse return die(g.d, "{s}: a unit has no target", .{pid});
        const src = val.getStr(target, "src_path") orelse return die(g.d, "{s}: the target has no src_path", .{pid});
        if (std.mem.startsWith(u8, pid, "registry+")) {
            const hash = std.mem.indexOfScalar(u8, pid, '#') orelse return die(g.d, "{s}: no #name@version in the package id", .{pid});
            const frag = pid[hash + 1 ..];
            const at = std.mem.lastIndexOfScalar(u8, frag, '@') orelse return die(g.d, "{s}: no name@version in the package id", .{pid});
            const name = frag[0..at];
            const ver = frag[at + 1 ..];
            const want = try std.fmt.allocPrint(g.a, "{s}-{s}", .{ name, ver });
            // /registry/src/<index>/<name>-<version>/
            var from: usize = 0;
            while (std.mem.indexOfPos(u8, src, from, "/registry/src/")) |m| {
                const idx_start = m + "/registry/src/".len;
                const idx_end = std.mem.indexOfScalarPos(u8, src, idx_start, '/') orelse break;
                const pkg_end = std.mem.indexOfScalarPos(u8, src, idx_end + 1, '/') orelse break;
                if (idx_end > idx_start and pkg_end > idx_end + 1) {
                    if (!std.mem.eql(u8, src[idx_end + 1 .. pkg_end], want)) break;
                    return .{ .name = name, .ver = ver, .registry = true, .rel = null, .root_file = src[pkg_end + 1 ..], .dir = src[0 .. pkg_end + 1] };
                }
                from = m + 1;
            }
            return die(g.d, "{s}: source path {s} is not in {s}-{s}", .{ pid, src, name, ver });
        }
        if (std.mem.startsWith(u8, pid, "path+file://")) {
            const hash = std.mem.indexOfScalar(u8, pid, '#') orelse return die(g.d, "{s}: no #version in the package id", .{pid});
            const dir = pid["path+file://".len..hash];
            const frag = pid[hash + 1 ..];
            if (!std.mem.startsWith(u8, dir, g.root)) return die(g.d, "{s}: path package outside the workspace (refused in v0)", .{pid});
            const rel = dir[g.root.len..];
            var name: []const u8 = undefined;
            var ver: []const u8 = undefined;
            if (std.mem.lastIndexOfScalar(u8, frag, '@')) |at| {
                name = frag[0..at];
                ver = frag[at + 1 ..];
            } else {
                name = if (std.mem.lastIndexOfScalar(u8, rel, '/')) |s| rel[s + 1 ..] else rel;
                ver = frag;
            }
            if (!(std.mem.startsWith(u8, src, dir) and src.len > dir.len and src[dir.len] == '/')) return die(g.d, "{s}: target {s} outside its package directory", .{ pid, src });
            return .{ .name = name, .ver = ver, .registry = false, .rel = rel, .root_file = src[dir.len + 1 ..], .dir = dir };
        }
        return die(g.d, "{s}: source kind not supported in v0 (git and alternate registries are refused)", .{pid});
    }
};

const Graph = struct {
    g: *Gen,
    scope: []const u8,
    verb: []const u8,
    raw: []const Value,
    roots: []const Value,
    ids: []?[]const u8,
    entry: std.StringArrayHashMap(Value),

    fn resolve(gr: *Graph, i: usize) Error![]const u8 {
        if (gr.ids[i]) |id| return id;
        const g = gr.g;
        const a = g.a;
        const u = gr.raw[i];
        const pkg = try g.pkgOf(u);
        const lk = g.lock.get(try std.fmt.allocPrint(a, "{s} {s}", .{ pkg.name, pkg.ver })) orelse
            return die(g.d, "{s} {s} is in the unit graph and not in Cargo.lock", .{ pkg.name, pkg.ver });
        var sha: ?[]const u8 = null;
        if (pkg.registry) {
            if (!isSha(lk.checksum)) return die(g.d, "{s} {s}: Cargo.lock has no sha256 checksum", .{ pkg.name, pkg.ver });
            sha = lk.checksum;
            if (!std.mem.startsWith(u8, lk.source, "registry+https://github.com/rust-lang/crates.io-index")) return die(g.d, "{s} {s}: only crates.io is supported in v0", .{ pkg.name, pkg.ver });
        } else if (lk.source.len != 0) {
            return die(g.d, "{s} {s}: path package has a source in Cargo.lock", .{ pkg.name, pkg.ver });
        }
        const t = val.get(u, "target").?;
        const prof = val.get(u, "profile") orelse return die(g.d, "{s} {s}: a unit has no profile", .{ pkg.name, pkg.ver });
        if (val.truthy(val.get(prof, "incremental"))) {
            const pn = val.getStr(prof, "name") orelse "dev";
            return die(g.d, "{s} {s}: the `{s}` profile has incremental compilation on, which a hermetic build cannot use: " ++
                "set `incremental = false` under [profile.{s}] in the root Cargo.toml (`buildrules init` writes it for dev)", .{ pkg.name, pkg.ver, pn, pn });
        }
        // [extern name, unit id]; a run-custom-build unit has several `build_script_build` (its own script, and the `links`
        // dependencies' outputs)
        var deps = std.ArrayList([2][]const u8).empty;
        for (val.items(val.get(u, "dependencies"))) |dep| {
            if (val.truthy(val.get(dep, "public")) or val.truthy(val.get(dep, "noprelude"))) {
                return die(g.d, "{s} {s}: a public/noprelude dependency edge (unstable features, refused in v0)", .{ pkg.name, pkg.ver });
            }
            const ext = val.getStr(dep, "extern_crate_name") orelse return die(g.d, "{s} {s}: a dependency has no extern_crate_name", .{ pkg.name, pkg.ver });
            const idx = val.get(dep, "index") orelse return die(g.d, "{s} {s}: a dependency has no index", .{ pkg.name, pkg.ver });
            if (idx != .integer or idx.integer < 0 or idx.integer >= gr.raw.len) return die(g.d, "{s} {s}: a dependency index is out of range", .{ pkg.name, pkg.ver });
            const did = try gr.resolve(@intCast(idx.integer));
            try deps.append(a, .{ ext, did });
        }
        std.mem.sort([2][]const u8, deps.items, {}, lessPair);
        var feats = std.ArrayList([]const u8).empty;
        for (val.items(val.get(u, "features"))) |f| try feats.append(a, val.asStr(f) orelse return die(g.d, "{s} {s}: a feature is not a string", .{ pkg.name, pkg.ver }));
        std.mem.sort([]const u8, feats.items, {}, lessStr);
        var cfgs = val.newArray(a);
        for (feats.items) |f| try val.push(&cfgs, val.str(try std.fmt.allocPrint(a, "feature=\"{s}\"", .{f})));
        var profile = val.newObject(a);
        for (profile_fields) |k| {
            const pv = val.get(prof, k) orelse return die(g.d, "{s} {s}: the profile has no `{s}`", .{ pkg.name, pkg.ver, k });
            try val.put(&profile, k, pv);
        }
        var depv = val.newArray(a);
        for (deps.items) |p| try val.push(&depv, try val.strList(a, &p));
        var body = val.newObject(a);
        try val.put(&body, "crate", val.str(pkg.name));
        try val.put(&body, "version", val.str(pkg.ver));
        try val.put(&body, "source", val.str(if (pkg.registry) "registry" else "path"));
        try val.put(&body, "target_kind", try sortedStrings(gr, val.get(t, "kind"), pkg, "kind"));
        try val.put(&body, "crate_types", try sortedStrings(gr, val.get(t, "crate_types"), pkg, "crate_types"));
        try val.put(&body, "target_name", val.str(val.getStr(t, "name") orelse return die(g.d, "{s} {s}: the target has no name", .{ pkg.name, pkg.ver })));
        try val.put(&body, "mode", val.str(val.getStr(u, "mode") orelse return die(g.d, "{s} {s}: a unit has no mode", .{ pkg.name, pkg.ver })));
        const plat = val.get(u, "platform");
        try val.put(&body, "side", val.str(if (plat == null or plat.? == .null) "exec" else "target"));
        try val.put(&body, "edition", val.str(val.getStr(t, "edition") orelse return die(g.d, "{s} {s}: the target has no edition", .{ pkg.name, pkg.ver })));
        try val.put(&body, "crate_root", val.str(pkg.root_file));
        try val.put(&body, "features", try val.strList(a, feats.items));
        try val.put(&body, "cfgs", cfgs);
        try val.put(&body, "profile", profile);
        try val.put(&body, "deps", depv);
        if (try g.packageLinks(pkg.dir)) |l| {
            if (l.len != 0) try val.put(&body, "links", val.str(l));
        }
        if (pkg.rel) |r| try val.put(&body, "path", val.str(r));
        if (sha) |s| try val.put(&body, "sha256", val.str(s));
        // `test` / `doctest` flags of the target change what a test action does.
        var flags = val.newObject(a);
        try val.put(&flags, "test", val.boolean(val.truthy(val.get(t, "test"))));
        try val.put(&flags, "doctest", val.boolean(val.truthy(val.get(t, "doctest"))));
        try val.put(&body, "test_flags", flags);
        const h = try val.contentId(a, body, 10);
        const uid = try std.fmt.allocPrint(a, "{s}-{s}:{s}", .{ pkg.name, pkg.ver, h });
        if (gr.entry.get(uid)) |prev| {
            if (!val.eql(prev, body)) return die(g.d, "content id collision on {s}", .{uid});
        }
        try gr.entry.put(uid, body);
        gr.ids[i] = uid;
        return uid;
    }
};

fn sortedStrings(gr: *Graph, v: ?Value, pkg: Pkg, what: []const u8) Error!Value {
    var l = std.ArrayList([]const u8).empty;
    for (val.items(v)) |x| try l.append(gr.g.a, val.asStr(x) orelse return die(gr.g.d, "{s} {s}: target {s} holds a non-string", .{ pkg.name, pkg.ver, what }));
    std.mem.sort([]const u8, l.items, {}, lessStr);
    return val.strList(gr.g.a, l.items);
}

fn lessPair(_: void, x: [2][]const u8, y: [2][]const u8) bool {
    const c = std.mem.order(u8, x[0], y[0]);
    if (c != .eq) return c == .lt;
    return std.mem.lessThan(u8, x[1], y[1]);
}

// ---- lints and policy --------------------------------------------------------------------------------------------

fn levelFlag(level: []const u8) ?[]const u8 {
    const names = [_][2][]const u8{ .{ "allow", "-A" }, .{ "warn", "-W" }, .{ "deny", "-D" }, .{ "forbid", "-F" }, .{ "force-warn", "--force-warn" } };
    for (names) |n| if (std.mem.eql(u8, n[0], level)) return n[1];
    return null;
}

const LintRow = struct { prio: i64, name: []const u8, level: []const u8, check: []const Value };

fn lintLess(_: void, x: LintRow, y: LintRow) bool {
    if (x.prio != y.prio) return x.prio < y.prio;
    return std.mem.lessThan(u8, y.name, x.name); // name descending
}

/// Cargo's `[lints.<tool>]` tables as compiler flags, ordered as cargo orders them (priority, then name descending). `rust` lints
/// go to every compile of a workspace member; `clippy` lints only to clippy-driver. rustdoc lints are not used.
pub fn lintFlags(a: std.mem.Allocator, d: *Diag, tables: ?Value, where: []const u8) Error!Value {
    var out = val.newObject(a);
    for ([_][]const u8{ "rust", "clippy" }) |tool| {
        var flags = val.newArray(a);
        var rows = std.ArrayList(LintRow).empty;
        const t = if (tables) |tv| val.get(tv, tool) else null;
        if (t) |tt| if (tt == .object) {
            var it = tt.object.iterator();
            while (it.next()) |e| {
                const name = e.key_ptr.*;
                const v = e.value_ptr.*;
                var level: []const u8 = "";
                var prio: i64 = 0;
                var check: []const Value = &.{};
                if (v == .string) {
                    level = v.string;
                } else if (v == .object) {
                    level = val.getStr(v, "level") orelse "";
                    if (val.get(v, "priority")) |p| {
                        if (p != .integer) return die(d, "{s}: lints.{s}.{s}: priority is not an integer", .{ where, tool, name });
                        prio = p.integer;
                    }
                    check = val.items(val.get(v, "check-cfg"));
                } else {
                    return die(d, "{s}: lints.{s}.{s}: is not a level or a table", .{ where, tool, name });
                }
                if (levelFlag(level) == null) return die(d, "{s}: lints.{s}.{s}: unknown level '{s}'", .{ where, tool, name, level });
                if (check.len != 0 and !(std.mem.eql(u8, tool, "rust") and std.mem.eql(u8, name, "unexpected_cfgs"))) {
                    return die(d, "{s}: lints.{s}.{s}: check-cfg only belongs to rust.unexpected_cfgs", .{ where, tool, name });
                }
                try rows.append(a, .{ .prio = prio, .name = name, .level = level, .check = check });
            }
        };
        std.mem.sort(LintRow, rows.items, {}, lintLess);
        for (rows.items) |r| {
            const full = if (std.mem.eql(u8, tool, "rust")) r.name else try std.fmt.allocPrint(a, "{s}::{s}", .{ tool, r.name });
            try val.push(&flags, val.str(levelFlag(r.level).?));
            try val.push(&flags, val.str(full));
            for (r.check) |c| {
                try val.push(&flags, val.str("--check-cfg"));
                try val.push(&flags, c);
            }
        }
        try val.put(&out, tool, flags);
    }
    return out;
}

/// The feature names cargo knows for a package: `[features]` keys plus optional dependencies not named with `dep:`.
pub fn declaredFeatures(a: std.mem.Allocator, doc: Value) Error![]const []const u8 {
    var names = std.StringArrayHashMap(void).init(a);
    var used = std.StringHashMap(void).init(a);
    if (val.get(doc, "features")) |f| if (f == .object) {
        var it = f.object.iterator();
        while (it.next()) |e| {
            try names.put(e.key_ptr.*, {});
            for (val.items(e.value_ptr.*)) |x| {
                if (x == .string and std.mem.startsWith(u8, x.string, "dep:")) try used.put(x.string[4..], {});
            }
        }
    };
    const secs = [_][]const u8{ "dependencies", "build-dependencies" };
    for (secs) |sec| try optionalDeps(val.get(doc, sec), &names, &used);
    if (val.get(doc, "target")) |tt| if (tt == .object) {
        var it = tt.object.iterator();
        while (it.next()) |e| {
            for (secs) |sec| try optionalDeps(val.get(e.value_ptr.*, sec), &names, &used);
        }
    };
    const out = try a.dupe([]const u8, names.keys());
    std.mem.sort([]const u8, out, {}, lessStr);
    return out;
}

fn optionalDeps(tbl: ?Value, names: *std.StringArrayHashMap(void), used: *std.StringHashMap(void)) !void {
    const t = tbl orelse return;
    if (t != .object) return;
    var it = t.object.iterator();
    while (it.next()) |e| {
        const v = e.value_ptr.*;
        if (v == .object and val.truthy(val.get(v, "optional")) and !used.contains(e.key_ptr.*)) try names.put(e.key_ptr.*, {});
    }
}

/// What cargo passes so `unexpected_cfgs` knows the package: `docsrs`, `test` and its own features.
pub fn checkCfgFlags(a: std.mem.Allocator, features: []const []const u8) Error!Value {
    var vals = std.ArrayList(u8).empty;
    for (features, 0..) |f, i| {
        if (i != 0) try vals.appendSlice(a, ", ");
        try vals.appendSlice(a, try val.quoted(a, f));
    }
    return val.strList(a, &.{ "--check-cfg", "cfg(docsrs,test)", "--check-cfg", try std.fmt.allocPrint(a, "cfg(feature, values({s}))", .{vals.items}) });
}

const policy_keys = [_][]const u8{ "actions", "default-action", "lint" };

/// `[*.metadata.buildrules]`: policy only (which steps chain into which action, lint strictness). Unknown keys are refused.
pub fn policyOf(a: std.mem.Allocator, d: *Diag, meta: ?Value, where: []const u8) Error!Value {
    const b = (if (meta) |m| val.get(m, "buildrules") else null) orelse return val.newObject(a);
    if (b != .object) return die(d, "{s}: metadata.buildrules is not a table", .{where});
    var bad = std.ArrayList([]const u8).empty;
    for (b.object.keys()) |k| {
        var known = false;
        for (policy_keys) |p| if (std.mem.eql(u8, p, k)) {
            known = true;
        };
        if (!known) try bad.append(a, k);
    }
    if (bad.items.len != 0) {
        std.mem.sort([]const u8, bad.items, {}, lessStr);
        return die(d, "{s}: unknown key(s) {s} in metadata.buildrules (known: ['actions', 'default-action', 'lint']); profiles and lints belong to cargo's own tables", .{ where, try pyList(a, bad.items) });
    }
    return b;
}

fn isStep(s: []const u8) bool {
    for (steps) |x| if (std.mem.eql(u8, x, s)) return true;
    return false;
}

/// An object copy of `base` with `over` laid over it (Python's `dict(base); d.update(over)`).
fn merged(a: std.mem.Allocator, base: ?Value, over: ?Value) !Value {
    var out = val.newObject(a);
    for ([_]?Value{ base, over }) |src| {
        if (src) |s| if (s == .object) {
            var it = s.object.iterator();
            while (it.next()) |e| try out.object.put(e.key_ptr.*, e.value_ptr.*);
        };
    }
    return out;
}

pub fn resolvePolicy(a: std.mem.Allocator, d: *Diag, ws: Value, pkg: Value, where: []const u8) Error!Value {
    const acts = try merged(a, val.get(ws, "actions"), val.get(pkg, "actions"));
    const steps_repr = "['lint', 'debug', 'test', 'release', 'coverage']";
    var it = acts.object.iterator();
    while (it.next()) |e| {
        const name = e.key_ptr.*;
        const list = e.value_ptr.*;
        if (isStep(name)) return die(d, "{s}: action '{s}' has the name of a step ({s}); name it differently", .{ where, name, steps_repr });
        var ok = list == .array and list.array.items.len != 0;
        if (ok) for (list.array.items) |x| {
            if (x != .string or !isStep(x.string)) ok = false;
        };
        if (!ok) return die(d, "{s}: action '{s}' must be a non-empty list of steps from {s}, got something else", .{ where, name, steps_repr });
    }
    const lint = try merged(a, val.get(ws, "lint"), val.get(pkg, "lint"));
    var bad_lint = std.ArrayList([]const u8).empty;
    for (lint.object.keys()) |k| if (!std.mem.eql(u8, k, "deny-warnings")) try bad_lint.append(a, k);
    if (bad_lint.items.len != 0) {
        std.mem.sort([]const u8, bad_lint.items, {}, lessStr);
        return die(d, "{s}: unknown lint policy key(s) {s}", .{ where, try pyList(a, bad_lint.items) });
    }
    const dflt: Value = val.get(pkg, "default-action") orelse val.get(ws, "default-action") orelse .null;
    if (dflt != .null) {
        const ds = if (dflt == .string) dflt.string else "";
        if (dflt != .string or (!acts.object.contains(ds) and !isStep(ds))) {
            return die(d, "{s}: default-action {s} is neither a step nor a defined action", .{ where, if (dflt == .string) try std.fmt.allocPrint(a, "'{s}'", .{ds}) else "?" });
        }
    }
    var out = val.newObject(a);
    try val.put(&out, "actions", try sortedObject(a, acts));
    try val.put(&out, "deny_warnings", val.boolean(val.truthy(val.get(lint, "deny-warnings"))));
    try val.put(&out, "default_action", dflt);
    return out;
}

fn sortedObject(a: std.mem.Allocator, o: Value) !Value {
    const keys = try a.dupe([]const u8, o.object.keys());
    std.mem.sort([]const u8, keys, {}, lessStr);
    var out = val.newObject(a);
    for (keys) |k| try out.object.put(k, o.object.get(k).?);
    return out;
}

fn readToml(a: std.mem.Allocator, d: *Diag, path: []const u8) Error!Value {
    const text = std.fs.cwd().readFileAlloc(a, path, 8 << 20) catch |e| return die(d, "cannot read {s}: {s}", .{ path, @errorName(e) });
    const doc = toml.parse(a, text);
    if (doc.msg.len != 0) return die(d, "{s}:{d}: {s}", .{ path, doc.line, doc.msg });
    return doc.value;
}

const Members = struct { packages: Value, workspace: Value };

fn lessUnit(_: void, x: Value, y: Value) bool {
    const c = std.mem.order(u8, val.getStr(x, "crate").?, val.getStr(y, "crate").?);
    if (c != .eq) return c == .lt;
    return std.mem.lessThan(u8, val.getStr(x, "version").?, val.getStr(y, "version").?);
}

/// Per workspace member: directory, lints and resolved policy, read from the Cargo.toml files.
fn packagesOf(a: std.mem.Allocator, d: *Diag, units: Value, root: []const u8) Error!Members {
    const base = std.mem.trimRight(u8, root, "/");
    const wsdoc = try readToml(a, d, try std.fmt.allocPrint(a, "{s}/Cargo.toml", .{base}));
    const wsec = val.get(wsdoc, "workspace") orelse val.newObject(a);
    const wspol = try policyOf(a, d, val.get(wsec, "metadata"), "[workspace.metadata]");
    var entries = std.ArrayList(Value).empty;
    for (units.object.values()) |e| try entries.append(a, e);
    std.mem.sort(Value, entries.items, {}, lessUnit);
    var out = val.newObject(a);
    for (entries.items) |e| {
        const crate = val.getStr(e, "crate").?;
        if (!std.mem.eql(u8, val.getStr(e, "source").?, "path") or out.object.contains(crate)) continue;
        const path = val.getStr(e, "path").?;
        const mp = try std.fmt.allocPrint(a, "{s}/{s}/Cargo.toml", .{ base, path });
        const doc = try readToml(a, d, mp);
        const where = try std.fmt.allocPrint(a, "{s}/Cargo.toml", .{path});
        const lt = val.get(doc, "lints") orelse val.newObject(a);
        var tables: Value = undefined;
        if (val.get(lt, "workspace")) |w| {
            if (w == .bool and w.bool) {
                tables = val.get(wsec, "lints") orelse val.newObject(a);
            } else {
                tables = try withoutKey(a, lt, "workspace");
            }
        } else {
            tables = lt;
        }
        const feats = try declaredFeatures(a, doc);
        const pkg_meta = if (val.get(doc, "package")) |p| val.get(p, "metadata") else null;
        const pol = try resolvePolicy(a, d, wspol, try policyOf(a, d, pkg_meta, try std.fmt.allocPrint(a, "[package.metadata] of {s}", .{where})), where);
        var row = val.newObject(a);
        try val.put(&row, "path", val.str(path));
        try val.put(&row, "version", val.str(val.getStr(e, "version").?));
        try val.put(&row, "check_cfg", try checkCfgFlags(a, feats));
        try val.put(&row, "lints", try lintFlags(a, d, tables, where));
        var pit = pol.object.iterator();
        while (pit.next()) |pe| try val.put(&row, pe.key_ptr.*, pe.value_ptr.*);
        try val.put(&out, crate, row);
    }
    // the workspace-level actions (a workspace may name an action no member overrides)
    const wpol = try resolvePolicy(a, d, wspol, val.newObject(a), "[workspace.metadata]");
    var wsrec = val.newObject(a);
    try val.put(&wsrec, "actions", val.get(wpol, "actions").?);
    try val.put(&wsrec, "default_action", val.get(wspol, "default-action") orelse .null);
    const clippy = try std.fmt.allocPrint(a, "{s}/clippy.toml", .{base});
    const has_clippy = if (std.fs.cwd().access(clippy, .{})) |_| true else |_| false;
    try val.put(&wsrec, "clippy_conf", if (has_clippy) val.str("clippy.toml") else .null);
    return .{ .packages = out, .workspace = wsrec };
}

fn withoutKey(a: std.mem.Allocator, o: Value, key: []const u8) !Value {
    var out = val.newObject(a);
    var it = o.object.iterator();
    while (it.next()) |e| if (!std.mem.eql(u8, e.key_ptr.*, key)) try out.object.put(e.key_ptr.*, e.value_ptr.*);
    return out;
}

