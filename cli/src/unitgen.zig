//! The unit-graph generator: cargo's `--unit-graph` JSON per member and verb, Cargo.lock and the manifests in, the committed
//! table `buildrules.lock.bzl` out (docs/contract.md, "The table"). `sync` calls it in process; nothing else runs.
//!
//! One entry in UNITS per distinct unit. Distinct means: same package, target, mode, exec/target side, features, profile
//! fields and (recursively) the same dependency units. A unit shared by two verbs is one entry, and that is the cache-sharing
//! fact: the entry's id is the content address of its body (the profile `name` is deliberately not part of it: rustc never sees
//! it). The output is deterministic, pure data (Starlark literals only), and carries no absolute path.

const std = @import("std");
const cargo_lock = @import("cargo_lock.zig");
const toml = @import("toml.zig");
const val = @import("val.zig");
const Diag = @import("diag.zig").Diag;
const Value = val.Value;

pub const Error = anyerror;

pub const header =
    "# Generated by `buildrules sync` from `cargo --unit-graph` and Cargo.lock. Do not edit.\n" ++
    "# One UNITS entry per distinct unit; GRAPHS and MEMBERS name the entries each cargo invocation needs.\n\n";

pub const profile_fields = [_][]const u8{
    "opt_level",        "lto",             "codegen_backend", "codegen_units", "debuginfo", "split_debuginfo",
    "debug_assertions", "overflow_checks", "rpath",           "incremental",   "panic",     "strip",
};

pub const steps = [_][]const u8{ "lint", "debug", "test", "release", "coverage" };
const components = [_][]const u8{ "cargo", "clippy", "rust_std", "rustc" }; // sorted

pub const GraphIn = struct { scope: []const u8, verb: []const u8, json: []const u8 };

pub const Input = struct {
    cargo_lock: []const u8,
    /// The directory cargo ran in: absolute paths are made relative to it, and its manifests are read.
    root: []const u8,
    graphs: []const GraphIn,
    rustc: []const u8,
    target: []const u8,
    /// rules/rust/pins.bzl (`RUST_VERSIONS`, `RUST_DEFAULT`).
    rust_pins: []const u8,
    /// toolchains/rust_pins.bzl (`EXTRA_RUST_VERSIONS`), when the repository has one.
    extra_pins: ?[]const u8 = null,
    /// Files under `root` whose sha256 the drift check compares.
    manifests: []const []const u8,
};

pub const Result = struct {
    /// The table, as `buildrules.lock.bzl`.
    text: []const u8,
    /// UNITS: an object, uid -> body.
    units: Value,
    toolchain: Value,
};

fn die(d: *Diag, comptime fmt: []const u8, args: anytype) error{Refused} {
    d.add("unitgen: " ++ fmt, args);
    return error.Refused;
}

fn sha256Hex(a: std.mem.Allocator, bytes: []const u8) ![]const u8 {
    var dg: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &dg, .{});
    return a.dupe(u8, &std.fmt.bytesToHex(dg, .lower));
}

fn lessStr(_: void, x: []const u8, y: []const u8) bool {
    return std.mem.lessThan(u8, x, y);
}

fn greaterStr(_: void, x: []const u8, y: []const u8) bool {
    return std.mem.lessThan(u8, y, x);
}

fn isSha(s: []const u8) bool {
    if (s.len != 64) return false;
    for (s) |c| if (!std.ascii.isDigit(c) and !(c >= 'a' and c <= 'f')) return false;
    return true;
}

/// The `[...]` Python prints for a list of strings: `['a', 'b']`.
fn pyList(a: std.mem.Allocator, xs: []const []const u8) ![]const u8 {
    var out = std.ArrayList(u8).empty;
    try out.append(a, '[');
    for (xs, 0..) |x, i| {
        if (i != 0) try out.appendSlice(a, ", ");
        try out.print(a, "'{s}'", .{x});
    }
    try out.append(a, ']');
    return out.toOwnedSlice(a);
}

