fn lessUid(_: void, x: []const u8, y: []const u8) bool {
    return std.mem.lessThan(u8, x, y);
}

pub fn generate(a: std.mem.Allocator, d: *Diag, in: Input) Error!Result {
    const toolchain = try resolveToolchain(a, d, in.rustc, in.rust_pins, in.extra_pins);
    var gen = Gen{
        .a = a,
        .d = d,
        .root = try std.fmt.allocPrint(a, "{s}/", .{std.mem.trimRight(u8, in.root, "/")}),
        .lock = std.StringHashMap(cargo_lock.Entry).init(a),
        .links = std.StringHashMap(?[]const u8).init(a),
    };
    var ldiag = Diag.init(a);
    const entries = cargo_lock.parse(a, "Cargo.lock", in.cargo_lock, &ldiag) catch {
        for (ldiag.msgs.items) |m| d.add("unitgen: {s}", .{m});
        d.lost += ldiag.lost;
        return error.Refused;
    };
    for (entries) |e| try gen.lock.put(try std.fmt.allocPrint(a, "{s} {s}", .{ e.name, e.version }), e);

    var graphs = std.ArrayList(*Graph).empty;
    for (in.graphs) |spec| {
        const parsed = std.json.parseFromSliceLeaky(Value, a, spec.json, .{}) catch |e| return die(d, "{s}:{s}: the unit graph is not JSON: {s}", .{ spec.scope, spec.verb, @errorName(e) });
        const ver = val.get(parsed, "version");
        if (ver == null or ver.? != .integer or ver.?.integer != 1) return die(d, "{s}:{s}: unit graph version is not 1 (only 1 is understood)", .{ spec.scope, spec.verb });
        const raw = val.items(val.get(parsed, "units"));
        const gr = try a.create(Graph);
        gr.* = .{ .g = &gen, .scope = spec.scope, .verb = spec.verb, .raw = raw, .roots = val.items(val.get(parsed, "roots")), .ids = try a.alloc(?[]const u8, raw.len), .entry = std.StringArrayHashMap(Value).init(a) };
        @memset(gr.ids, null);
        for (0..raw.len) |i| _ = try gr.resolve(i);
        try graphs.append(a, gr);
    }

    var units = std.StringArrayHashMap(Value).init(a);
    for (graphs.items) |gr| {
        var it = gr.entry.iterator();
        while (it.next()) |e| {
            if (units.get(e.key_ptr.*)) |prev| {
                if (!val.eql(prev, e.value_ptr.*)) return die(d, "content id collision across graphs on {s}", .{e.key_ptr.*});
            } else try units.put(e.key_ptr.*, e.value_ptr.*);
        }
    }

    var ws = val.newObject(a);
    var members = val.newObject(a);
    for (graphs.items) |gr| {
        var roots = std.ArrayList([]const u8).empty;
        for (gr.roots) |r| {
            if (r != .integer or r.integer < 0 or r.integer >= gr.ids.len) return die(d, "{s}:{s}: a root index is out of range", .{ gr.scope, gr.verb });
            const id = gr.ids[@intCast(r.integer)].?;
            var seen = false;
            for (roots.items) |x| if (std.mem.eql(u8, x, id)) {
                seen = true;
            };
            if (!seen) try roots.append(a, id);
        }
        std.mem.sort([]const u8, roots.items, {}, lessStr);
        var distinct = std.StringHashMap(void).init(a);
        for (gr.ids) |id| try distinct.put(id.?, {});
        var rec = val.newObject(a);
        try val.put(&rec, "units", val.int(@intCast(distinct.count())));
        try val.put(&rec, "graph_units", val.int(@intCast(gr.ids.len)));
        try val.put(&rec, "roots", try val.strList(a, roots.items));
        if (std.mem.eql(u8, gr.scope, "*")) {
            try val.put(&ws, gr.verb, rec);
        } else {
            const gop = try members.object.getOrPut(gr.scope);
            if (!gop.found_existing) gop.value_ptr.* = val.newObject(a);
            try val.put(gop.value_ptr, gr.verb, rec);
        }
    }

    var units_v = val.newObject(a);
    {
        const keys = try a.dupe([]const u8, units.keys());
        std.mem.sort([]const u8, keys, {}, lessUid);
        for (keys) |k| try units_v.object.put(k, units.get(k).?);
    }
    const pk = try packagesOf(a, d, units_v, in.root);

    var aw = std.Io.Writer.Allocating.init(a);
    const w = &aw.writer;
    try w.writeAll(header);
    try w.writeAll("SCHEMA = 2\n");
    try w.print("RUSTC = {s}\nTARGET = {s}\n", .{ try val.quoted(a, in.rustc), try val.quoted(a, in.target) });
    try w.print("CARGO_LOCK_SHA256 = {s}\n", .{try val.quoted(a, try sha256Hex(a, in.cargo_lock))});
    const mf = try a.dupe([]const u8, in.manifests);
    std.mem.sort([]const u8, mf, {}, lessStr);
    // One `    "path": "sha256",` line per file (the contract: the Zig CLI's `check` reads these lines; docs/contract.md).
    try w.writeAll("MANIFEST_SHA256 = {\n");
    var last: ?[]const u8 = null;
    for (mf) |m| {
        if (last != null and std.mem.eql(u8, last.?, m)) continue;
        last = m;
        const path = try std.fmt.allocPrint(a, "{s}/{s}", .{ std.mem.trimRight(u8, in.root, "/"), m });
        const bytes = std.fs.cwd().readFileAlloc(a, path, 64 << 20) catch |e| return die(d, "cannot read {s}: {s}", .{ path, @errorName(e) });
        try w.print("    {s}: {s},\n", .{ try val.quoted(a, m), try val.quoted(a, try sha256Hex(a, bytes)) });
    }
    try w.writeAll("}\n\n");
    try w.writeAll("# The Rust toolchain this table was made for and the hashes it was pinned with (buildrules' own pins, or buildrules-pins.toml).\n");
    try w.writeAll("# The rules refuse a table whose hashes are not the pinned ones, so a pin bump is a visible diff here.\n");
    try w.writeAll("TOOLCHAIN = ");
    try val.lit(w, a, toolchain, 0);
    try w.writeAll("\n\n# Policy read from [workspace.metadata.buildrules] and clippy.toml; lints from [workspace.lints]; both baked here.\n");
    try w.writeAll("WORKSPACE = ");
    try val.lit(w, a, pk.workspace, 0);
    try w.writeAll("\n\n# One row per member: its directory, `[lints]` as flags, and `[package.metadata.buildrules]` resolved over the workspace's.\n");
    try w.writeAll("PACKAGES = ");
    try val.lit(w, a, pk.packages, 0);
    try w.writeAll("\n\n# `cargo <verb> --workspace --target TARGET`: the roots and the number of units the graph holds.\n");
    try w.writeAll("GRAPHS = ");
    try val.lit(w, a, ws, 0);
    try w.writeAll("\n\n# `cargo <verb> -p <member> --target TARGET`, per member.\n");
    try w.writeAll("MEMBERS = ");
    try val.lit(w, a, members, 0);
    try w.writeAll("\n\nUNITS = {\n");
    for (units_v.object.keys(), units_v.object.values()) |k, v| {
        try w.print("    {s}: ", .{try val.quoted(a, k)});
        try val.lit(w, a, v, 1);
        try w.writeAll(",\n");
    }
    try w.writeAll("}\n");
    return .{ .text = aw.written(), .units = units_v, .toolchain = toolchain };
}
