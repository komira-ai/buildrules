/// The TOOLCHAIN record for `version`: buildrules' own pin, else the repository's, else a refusal that says how to add one.
pub fn resolveToolchain(a: std.mem.Allocator, d: *Diag, version: []const u8, pins_text: []const u8, extra_text: ?[]const u8) Error!Value {
    const builtin = (val.readNamed(a, pins_text, "RUST_VERSIONS") catch return die(d, "rules/rust/pins.bzl: RUST_VERSIONS is not a literal", .{})) orelse
        return die(d, "rules/rust/pins.bzl: no RUST_VERSIONS", .{});
    const default = (val.readNamed(a, pins_text, "RUST_DEFAULT") catch return die(d, "rules/rust/pins.bzl: RUST_DEFAULT is not a literal", .{})) orelse
        return die(d, "rules/rust/pins.bzl: no RUST_DEFAULT", .{});
    var extra: ?Value = null;
    if (extra_text) |t| {
        extra = (val.readNamed(a, t, "EXTRA_RUST_VERSIONS") catch return die(d, "toolchains/rust_pins.bzl: EXTRA_RUST_VERSIONS is not a literal", .{})) orelse
            return die(d, "toolchains/rust_pins.bzl: no EXTRA_RUST_VERSIONS", .{});
    }
    var origin: []const u8 = "builtin";
    var row: Value = undefined;
    if (val.get(builtin, version)) |r| {
        row = r;
    } else if (extra != null and val.get(extra.?, version) != null) {
        row = val.get(extra.?, version).?;
        origin = "buildrules-pins.toml";
    } else {
        var known = std.ArrayList(u8).empty;
        if (builtin == .object) {
            var first = true;
            for (builtin.object.keys()) |k| {
                if (!first) try known.appendSlice(a, ", ");
                first = false;
                try known.appendSlice(a, k);
            }
        }
        return die(d, "rust-toolchain.toml pins rustc {s}, which buildrules does not pin (it pins {s}) and " ++
            "buildrules-pins.toml does not supply. Use one of those versions, or add to buildrules-pins.toml, with the sha256 and size " ++
            "of each tarball (https://static.rust-lang.org/dist/rustc-{s}-x86_64-unknown-linux-gnu.tar.gz and the others):\n" ++
            "  [rust.\"{s}\".rustc]\n  sha256 = \"<64 hex>\"\n  size = <bytes>\n" ++
            "  (and the same for [rust.\"{s}\".rust-std], .cargo and .clippy)", .{ version, known.items, version, version, version });
    }
    var sha = val.newObject(a);
    for (components) |c| {
        const comp = val.get(row, c) orelse return die(d, "the pin of rustc {s} has no {s}", .{ version, c });
        const h = val.getStr(comp, "sha256") orelse return die(d, "the pin of rustc {s}: {s} has no sha256", .{ version, c });
        try val.put(&sha, c, val.str(h));
    }
    var rec = val.newObject(a);
    try val.put(&rec, "version", val.str(version));
    try val.put(&rec, "origin", val.str(origin));
    try val.put(&rec, "default", val.boolean(default == .string and std.mem.eql(u8, default.string, version)));
    try val.put(&rec, "sha256", sha);
    return rec;
}

