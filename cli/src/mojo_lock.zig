//! buildrules.mojo.lock.bzl: the unit graph of one package, as mopm printed it, plus what `buildrules mojo check` needs to tell
//! whether it is still the graph of the files on disk (docs/contract.md, section 12). Pure Starlark data:
//!
//!     SCHEMA = 1
//!     MOPM = {"version": "0.0.48", "origin": "builtin"}      # and , "workspace_root": True for a mopm that was given --workspace-root (Starlark's True)
//!     MOJO = "1.0.0"
//!     CLOSURE_SHA256 = "<mopm's hash of the toolchain closure, a second copy of the graph's>"
//!     MANIFEST_SHA256 = {"mopm.toml": "<sha256>", ...}
//!     GRAPH_JSON = r'''<mopm plan --unit-graph --locked, path dependencies by identity only (rules/mojo/tools/graph_norm.zig)>'''
//!     GRAPH = json.decode(GRAPH_JSON)
//!     GRAPH_JSON_LINUX_AARCH64 = r'''<the same for plan --subdir linux-aarch64>'''     # and GRAPH_JSON_OSX_ARM64, only when mopm takes --subdir
//!     GRAPHS = {"linux-64": GRAPH, "linux-aarch64": json.decode(GRAPH_JSON_LINUX_AARCH64), ...}
//!
//! The graph text is mopm's, line for line, but for the sources and keys of path dependencies (their own tables hold those), so reviewing
//! the diff of the table is reviewing mopm's output, and `check` reads the same bytes the rules do.

const std = @import("std");
const valid = @import("valid.zig");
const Diag = @import("diag.zig").Diag;

pub const Manifest = struct { path: []const u8, sha256: []const u8 };

pub const Lock = struct {
    schema: u32,
    mopm_version: []const u8,
    mopm_origin: []const u8,
    /// The graph was asked for with `--workspace-root` (its paths are relative to the cell root, not to the package). Written only when true, so a
    /// table made before the flag existed is unchanged.
    workspace_root: bool = false,
    mojo: []const u8,
    closure_sha256: []const u8,
    manifests: []const Manifest,
    /// The graph of `linux-64` (`GRAPH`, which a table made before graphs per subdir existed holds alone).
    graph_json: []const u8,
    /// The graphs of the other subdirs, in the order of `extra_subdirs`: `GRAPH_JSON_<SUBDIR>` blocks and the `GRAPHS` table that names them all. Empty
    /// when mopm was not asked for them, and then the table is byte for byte what it was.
    extra: []const SubGraph = &.{},
};

/// The subdir whose graph is `GRAPH` (mopm's default) and the others `sync` asks mopm for with `plan --subdir`, in the order they are written.
pub const base_subdir = "linux-64";
pub const extra_subdirs = [_][]const u8{ "linux-aarch64", "osx-arm64" };

pub const SubGraph = struct { subdir: []const u8, graph_json: []const u8 };

/// `linux-aarch64` -> `GRAPH_JSON_LINUX_AARCH64`: the name of the Starlark variable that holds the graph of a subdir.
pub fn graphVar(a: std.mem.Allocator, subdir: []const u8) ![]u8 {
    const prefix = "GRAPH_JSON_";
    const out = try a.alloc(u8, prefix.len + subdir.len);
    @memcpy(out[0..prefix.len], prefix);
    for (subdir, 0..) |c, i| out[prefix.len + i] = if (c == '-') '_' else std.ascii.toUpper(c);
    return out;
}

/// What follows the origin on the MOPM line of a table whose graph was asked for with --workspace-root. Starlark's boolean is `True`.
const workspace_root_tail = ", \"workspace_root\": True}";

const graph_open = "GRAPH_JSON = r'''";
const graph_close = "'''\n";

pub const header = "# Generated by `buildrules mojo sync`. Do not edit.\n" ++
    "# The unit graph of this package for the Mojo version of mopm-toolchain.toml: mopm's own output (docs/contract.md, section 12).\n";

/// `<open><graph>` and the closing quotes, the graph ending in a newline.
fn appendGraph(a: std.mem.Allocator, o: *std.ArrayList(u8), open: []const u8, graph: []const u8) !void {
    try o.appendSlice(a, open);
    try o.appendSlice(a, graph);
    if (graph.len == 0 or graph[graph.len - 1] != '\n') try o.append(a, '\n');
    try o.appendSlice(a, graph_close);
}

pub fn render(a: std.mem.Allocator, l: Lock) ![]u8 {
    var o = std.ArrayList(u8).empty;
    try o.appendSlice(a, header);
    try o.print(a, "SCHEMA = {d}\n", .{l.schema});
    try o.print(a, "MOPM = {{\"version\": \"{s}\", \"origin\": \"{s}\"{s}\n", .{ l.mopm_version, l.mopm_origin, if (l.workspace_root) workspace_root_tail else "}" });
    try o.print(a, "MOJO = \"{s}\"\n", .{l.mojo});
    try o.print(a, "CLOSURE_SHA256 = \"{s}\"\n", .{l.closure_sha256});
    try o.appendSlice(a, "MANIFEST_SHA256 = {\n");
    for (l.manifests) |m| try o.print(a, "    \"{s}\": \"{s}\",\n", .{ m.path, m.sha256 });
    try o.appendSlice(a, "}\n");
    try appendGraph(a, &o, graph_open, l.graph_json);
    try o.appendSlice(a, "GRAPH = json.decode(GRAPH_JSON)\n");
    if (l.extra.len > 0) {
        for (l.extra) |x| {
            try appendGraph(a, &o, try std.fmt.allocPrint(a, "{s}{s}", .{ try graphVar(a, x.subdir), graph_open["GRAPH_JSON".len..] }), x.graph_json);
        }
        try o.appendSlice(a, "GRAPHS = {\n    \"" ++ base_subdir ++ "\": GRAPH,\n");
        for (l.extra) |x| try o.print(a, "    \"{s}\": json.decode({s}),\n", .{ x.subdir, try graphVar(a, x.subdir) });
        try o.appendSlice(a, "}\n");
    }
    return o.toOwnedSlice(a);
}

/// What `render` writes: line formats are fixed, so a reader is a few prefix matches. Every problem goes into `diag`.
pub fn parse(a: std.mem.Allocator, name: []const u8, text: []const u8, diag: *Diag) error{Invalid}!Lock {
    const before = diag.count();
    var l = Lock{ .schema = 0, .mopm_version = "", .mopm_origin = "", .mojo = "", .closure_sha256 = "", .manifests = &.{}, .graph_json = "" };
    const gi = std.mem.indexOf(u8, text, graph_open) orelse {
        diag.add("{s}: no GRAPH_JSON = r'''...''' block", .{name});
        return error.Invalid;
    };
    const body = gi + graph_open.len;
    const ge = std.mem.indexOfPos(u8, text, body, graph_close) orelse {
        diag.add("{s}: the GRAPH_JSON block is not closed", .{name});
        return error.Invalid;
    };
    l.graph_json = text[body..ge];
    var extra = std.ArrayList(SubGraph).empty;
    for (extra_subdirs) |sd| {
        const open = std.fmt.allocPrint(a, "\n{s}{s}", .{ graphVar(a, sd) catch return error.Invalid, graph_open["GRAPH_JSON".len..] }) catch return error.Invalid;
        const at = std.mem.indexOfPos(u8, text, ge, open) orelse continue;
        const eb = at + open.len;
        const ee = std.mem.indexOfPos(u8, text, eb, graph_close) orelse {
            diag.add("{s}: the {s} block is not closed", .{ name, open[1 .. open.len - "= r'''".len - 1] });
            return error.Invalid;
        };
        extra.append(a, .{ .subdir = sd, .graph_json = text[eb..ee] }) catch return error.Invalid;
    }
    l.extra = extra.items;
    var ms = std.ArrayList(Manifest).empty;
    var in_manifests = false;
    var it = std.mem.splitScalar(u8, text[0..gi], '\n');
    while (it.next()) |line| {
        if (in_manifests) {
            if (std.mem.eql(u8, line, "}")) {
                in_manifests = false;
                continue;
            }
            // `    "path": "sha",`
            const t = std.mem.trim(u8, line, " ,");
            const sep = std.mem.indexOf(u8, t, "\": \"") orelse {
                diag.add("{s}: cannot read the MANIFEST_SHA256 line {s}", .{ name, line });
                continue;
            };
            if (t.len < 2 or t[0] != '"' or t[t.len - 1] != '"') {
                diag.add("{s}: cannot read the MANIFEST_SHA256 line {s}", .{ name, line });
                continue;
            }
            ms.append(a, .{ .path = t[1..sep], .sha256 = t[sep + 4 .. t.len - 1] }) catch return error.Invalid;
        } else if (std.mem.startsWith(u8, line, "SCHEMA = ")) {
            l.schema = std.fmt.parseInt(u32, line["SCHEMA = ".len..], 10) catch 0;
        } else if (std.mem.startsWith(u8, line, "MOPM = {\"version\": \"")) {
            const rest = line["MOPM = {\"version\": \"".len..];
            const q = std.mem.indexOfScalar(u8, rest, '"') orelse continue;
            l.mopm_version = rest[0..q];
            const mark = "\"origin\": \"";
            const oi = std.mem.indexOf(u8, rest, mark) orelse continue;
            const o2 = rest[oi + mark.len ..];
            const q2 = std.mem.indexOfScalar(u8, o2, '"') orelse continue;
            l.mopm_origin = o2[0..q2];
            // After the origin: `}`, or `, "workspace_root": True}`. The table is Starlark, whose boolean is `True`: Buck2 cannot load a table that
            // says `true`, so it is refused here instead of being read as "not rooted".
            const tail = o2[q2 + 1 ..];
            if (std.mem.eql(u8, tail, workspace_root_tail)) {
                l.workspace_root = true;
            } else if (std.mem.indexOf(u8, tail, "workspace_root") != null) {
                diag.add("{s}: the MOPM line is not `{{..., \"origin\": \"...\"{s}`: Starlark spells the boolean True, so a lowercase true is not a name Buck2 knows, and the table cannot be loaded. Run `buildrules mojo sync`", .{ name, workspace_root_tail });
            }
        } else if (std.mem.startsWith(u8, line, "MOJO = \"")) {
            l.mojo = std.mem.trimRight(u8, line["MOJO = \"".len..], "\"");
        } else if (std.mem.startsWith(u8, line, "CLOSURE_SHA256 = \"")) {
            l.closure_sha256 = std.mem.trimRight(u8, line["CLOSURE_SHA256 = \"".len..], "\"");
        } else if (std.mem.eql(u8, line, "MANIFEST_SHA256 = {")) {
            in_manifests = true;
        }
    }
    l.manifests = ms.toOwnedSlice(a) catch return error.Invalid;
    if (l.schema == 0) diag.add("{s}: no SCHEMA", .{name});
    if (l.mopm_version.len == 0) diag.add("{s}: no MOPM", .{name});
    if (l.mojo.len == 0) diag.add("{s}: no MOJO", .{name});
    if (!valid.isSha256(l.closure_sha256)) diag.add("{s}: CLOSURE_SHA256 is not a sha256", .{name});
    if (diag.count() != before) return error.Invalid;
    return l;
}

pub fn manifestHash(l: Lock, path: []const u8) ?[]const u8 {
    for (l.manifests) |m| if (std.mem.eql(u8, m.path, path)) return m.sha256;
    return null;
}

// ---- the graph ---------------------------------------------------------------------------------------

pub const Src = struct { path: []const u8, sha256: []const u8 };

/// An entry of a unit's `natives` that a workspace member builds: the library, and the id of the native unit that builds it.
pub const Built = struct { soname: []const u8, unit: []const u8 };

pub const Unit = struct {
    id: []const u8,
    package: []const u8,
    kind: []const u8,
    root: []const u8,
    srcs: []const Src,
    built: []const Built = &.{},
};

pub const Graph = struct {
    package: []const u8,
    mojo: []const u8,
    closure_sha256: []const u8,
    /// The `toolchain` object, re-printed in one fixed layout: what two graphs of one Mojo version must agree on.
    toolchain: std.json.Value,
    units: []const Unit,
};

fn str(v: std.json.Value) ?[]const u8 {
    return switch (v) {
        .string => |s| s,
        else => null,
    };
}

fn field(o: std.json.ObjectMap, k: []const u8) ?std.json.Value {
    return o.get(k);
}

pub fn parseGraph(a: std.mem.Allocator, name: []const u8, text: []const u8, diag: *Diag) error{Invalid}!Graph {
    const root = std.json.parseFromSliceLeaky(std.json.Value, a, text, .{}) catch {
        diag.add("{s}: the GRAPH_JSON block is not JSON", .{name});
        return error.Invalid;
    };
    const o = switch (root) {
        .object => |x| x,
        else => {
            diag.add("{s}: the unit graph is not a JSON object", .{name});
            return error.Invalid;
        },
    };
    const version = field(o, "unit_graph") orelse {
        diag.add("{s}: the unit graph has no `unit_graph` format number", .{name});
        return error.Invalid;
    };
    if (version != .integer or (version.integer != 1 and version.integer != 2)) {
        diag.add("{s}: unit_graph format is not 1 or 2 (this buildrules reads 1, and 2, which adds the native unit of a member's own library)", .{name});
        return error.Invalid;
    }
    const pkg = str(field(o, "package") orelse .null) orelse "";
    const mojo = str(field(o, "mojo") orelse .null) orelse "";
    const tc = field(o, "toolchain") orelse std.json.Value.null;
    const tco = switch (tc) {
        .object => |x| x,
        else => {
            diag.add("{s}: the unit graph has no `toolchain` object", .{name});
            return error.Invalid;
        },
    };
    const closure = str(field(tco, "closure_sha256") orelse .null) orelse "";
    const units_v = field(o, "units") orelse std.json.Value.null;
    const arr = switch (units_v) {
        .array => |x| x.items,
        else => {
            diag.add("{s}: the unit graph has no `units` array", .{name});
            return error.Invalid;
        },
    };
    var units = std.ArrayList(Unit).empty;
    for (arr) |uv| {
        const uo = switch (uv) {
            .object => |x| x,
            else => {
                diag.add("{s}: a unit is not an object", .{name});
                return error.Invalid;
            },
        };
        var srcs = std.ArrayList(Src).empty;
        if (field(uo, "srcs")) |sv| {
            if (sv == .array) {
                for (sv.array.items) |s| {
                    if (s != .object) continue;
                    const p = str(field(s.object, "path") orelse .null) orelse continue;
                    const h = str(field(s.object, "sha256") orelse .null) orelse continue;
                    srcs.append(a, .{ .path = p, .sha256 = h }) catch return error.Invalid;
                }
            }
        }
        var built = std.ArrayList(Built).empty;
        if (field(uo, "natives")) |nv| {
            if (nv == .array) {
                for (nv.array.items) |n| {
                    if (n != .object) continue;
                    const b = str(field(n.object, "built") orelse .null) orelse continue;
                    if (b.len == 0) continue;
                    built.append(a, .{ .soname = str(field(n.object, "soname") orelse .null) orelse "", .unit = b }) catch return error.Invalid;
                }
            }
        }
        units.append(a, .{
            .id = str(field(uo, "id") orelse .null) orelse "",
            .package = str(field(uo, "package") orelse .null) orelse "",
            .kind = str(field(uo, "kind") orelse .null) orelse "",
            .root = str(field(uo, "root") orelse .null) orelse "",
            .srcs = srcs.toOwnedSlice(a) catch return error.Invalid,
            .built = built.toOwnedSlice(a) catch return error.Invalid,
        }) catch return error.Invalid;
    }
    // A native a member builds is a unit of the graph (`native:<package>/<id>`), and every entry that says `built` names one: a graph in which an entry
    // names a unit that is not there cannot be linked, and the rules would only find that out when a test fails to link.
    const before = diag.count();
    for (units.items) |u| {
        for (u.built) |b| {
            var found = false;
            for (units.items) |other| {
                if (std.mem.eql(u8, other.id, b.unit)) found = true;
            }
            if (!found) diag.add("{s}: {s} links the native library {s}, built by {s}, but the graph has no such native unit", .{ name, u.id, b.soname, b.unit });
        }
    }
    if (diag.count() != before) return error.Invalid;
    return .{ .package = pkg, .mojo = mojo, .closure_sha256 = closure, .toolchain = tc, .units = units.toOwnedSlice(a) catch return error.Invalid };
}

// ---- toolchains/mojo_pins.bzl ----------------------------------------------------------------------------

pub const pins_header = "# Generated by `buildrules mojo sync` from mopm's unit graphs. Do not edit.\n" ++
    "# The Mojo toolchains this repository builds with: mopm's `toolchain` section, verbatim (docs/contract.md, section 12).\n";

pub const pins_empty = pins_header ++ "MOJO_TOOLCHAINS = {}\n";

const Check = struct {
    fn string(d: *Diag, what: []const u8, v: ?std.json.Value, comptime ok: fn ([]const u8) bool) ?[]const u8 {
        const s = if (v) |x| str(x) else null;
        if (s == null or !ok(s.?)) {
            d.add("the unit graph's toolchain: {s} is missing or has characters a table may not carry", .{what});
            return null;
        }
        return s;
    }
};

fn isTriple(s: []const u8) bool {
    if (s.len == 0 or s.len > 64) return false;
    for (s) |c| if (!((c >= 'a' and c <= 'z') or (c >= '0' and c <= '9') or c == '_' or c == '-' or c == '.')) return false;
    return true;
}

fn isName(s: []const u8) bool {
    return valid.isToken(s);
}

fn sizeOf(v: ?std.json.Value) ?i64 {
    const x = v orelse return null;
    return if (x == .integer and x.integer > 0) x.integer else null;
}

/// One toolchain object as a Starlark dict entry, or null with the reason in `diag`.
fn renderToolchain(a: std.mem.Allocator, d: *Diag, o: *std.ArrayList(u8), tc: std.json.Value) !bool {
    const before = d.count();
    const t = if (tc == .object) tc.object else {
        d.add("the unit graph's toolchain is not an object", .{});
        return false;
    };
    const subdir = Check.string(d, "subdir", t.get("subdir"), isName);
    const cc = Check.string(d, "cc_target", t.get("cc_target"), isTriple);
    const closure = Check.string(d, "closure_sha256", t.get("closure_sha256"), valid.isSha256);
    const zig = if (t.get("zig")) |z| (if (z == .object) z.object else null) else null;
    if (zig == null) d.add("the unit graph's toolchain has no zig", .{});
    if (subdir == null or cc == null or closure == null or zig == null) return false;
    const zv = Check.string(d, "zig.version", zig.?.get("version"), valid.isVersion);
    const zu = Check.string(d, "zig.url", zig.?.get("url"), valid.isUrl);
    const zs = Check.string(d, "zig.sha256", zig.?.get("sha256"), valid.isSha256);
    const zz = sizeOf(zig.?.get("size"));
    if (zz == null) d.add("the unit graph's toolchain: zig.size is missing", .{});
    const comps = if (t.get("components")) |c| (if (c == .array) c.array.items else null) else null;
    if (comps == null) d.add("the unit graph's toolchain has no components", .{});
    if (zv == null or zu == null or zs == null or zz == null or comps == null) return false;
    try o.print(a, "        \"subdir\": \"{s}\",\n        \"cc_target\": \"{s}\",\n        \"closure_sha256\": \"{s}\",\n", .{ subdir.?, cc.?, closure.? });
    try o.print(a, "        \"zig\": {{\"version\": \"{s}\", \"url\": \"{s}\", \"sha256\": \"{s}\", \"size\": {d}}},\n", .{ zv.?, zu.?, zs.?, zz.? });
    try o.appendSlice(a, "        \"components\": [\n");
    for (comps.?) |cv| {
        if (cv != .object) {
            d.add("the unit graph's toolchain: a component is not an object", .{});
            continue;
        }
        const n = Check.string(d, "component name", cv.object.get("name"), isName);
        const v = Check.string(d, "component version", cv.object.get("version"), valid.isVersion);
        const u = Check.string(d, "component url", cv.object.get("url"), valid.isUrl);
        const s = Check.string(d, "component sha256", cv.object.get("sha256"), valid.isSha256);
        const z = sizeOf(cv.object.get("size"));
        if (z == null) d.add("the unit graph's toolchain: a component has no size", .{});
        if (n == null or v == null or u == null or s == null or z == null) continue;
        try o.print(a, "            {{\"name\": \"{s}\", \"version\": \"{s}\", \"url\": \"{s}\", \"sha256\": \"{s}\", \"size\": {d}}},\n", .{ n.?, v.?, u.?, s.?, z.? });
    }
    try o.appendSlice(a, "        ],\n");
    return d.count() == before;
}

pub const Tc = struct { mojo: []const u8, toolchain: std.json.Value, subdir: []const u8 = base_subdir };

/// toolchains/mojo_pins.bzl for the toolchains of the graphs: one entry of `MOJO_TOOLCHAINS` per Mojo version and subdir (two graphs of one version and
/// subdir must have the same toolchain object). The key of a linux-64 entry is the version, as it always was; the key of another subdir's is
/// `<version>@<subdir>` (`1.0.0@linux-aarch64`), which `mojo_toolchains()` declares as `mojo_1_0_0_linux_aarch64`. Sorted by version, then by subdir with
/// linux-64 first. Without graphs for other subdirs the file is what it was before they existed.
pub fn renderPins(a: std.mem.Allocator, tcs: []const Tc, diag: *Diag) error{Invalid}![]const u8 {
    const before = diag.count();
    var order = std.ArrayList(usize).empty;
    for (tcs, 0..) |x, i| {
        var seen: ?usize = null;
        for (order.items) |j| if (std.mem.eql(u8, tcs[j].mojo, x.mojo) and std.mem.eql(u8, tcs[j].subdir, x.subdir)) {
            seen = j;
        };
        if (seen) |j| {
            if (!jsonEqual(a, tcs[j].toolchain, x.toolchain)) {
                diag.add("two packages' unit graphs pin different toolchains for Mojo {s}{s}{s}: mopm pins one", .{ x.mojo, if (std.mem.eql(u8, x.subdir, base_subdir)) "" else " on ", if (std.mem.eql(u8, x.subdir, base_subdir)) "" else x.subdir });
            }
            continue;
        }
        order.append(a, i) catch return error.Invalid;
    }
    if (diag.count() != before) return error.Invalid;
    std.mem.sort(usize, order.items, tcs, struct {
        fn lt(ctx: []const Tc, x: usize, y: usize) bool {
            if (!std.mem.eql(u8, ctx[x].mojo, ctx[y].mojo)) return std.mem.lessThan(u8, ctx[x].mojo, ctx[y].mojo);
            return std.mem.lessThan(u8, ctx[x].subdir, ctx[y].subdir);
        }
    }.lt);
    var o = std.ArrayList(u8).empty;
    o.appendSlice(a, pins_header) catch return error.Invalid;
    if (order.items.len == 0) {
        o.appendSlice(a, "MOJO_TOOLCHAINS = {}\n") catch return error.Invalid;
        return o.toOwnedSlice(a) catch error.Invalid;
    }
    o.appendSlice(a, "MOJO_TOOLCHAINS = {\n") catch return error.Invalid;
    for (order.items) |i| {
        if (!valid.isVersion(tcs[i].mojo)) {
            diag.add("Mojo version {s} has characters a table may not carry", .{tcs[i].mojo});
            continue;
        }
        if (std.mem.eql(u8, tcs[i].subdir, base_subdir)) {
            o.print(a, "    \"{s}\": {{\n", .{tcs[i].mojo}) catch return error.Invalid;
        } else {
            o.print(a, "    \"{s}@{s}\": {{\n", .{ tcs[i].mojo, tcs[i].subdir }) catch return error.Invalid;
        }
        const ok = renderToolchain(a, diag, &o, tcs[i].toolchain) catch return error.Invalid;
        if (!ok) continue;
        o.appendSlice(a, "    },\n") catch return error.Invalid;
    }
    if (diag.count() != before) return error.Invalid;
    o.appendSlice(a, "}\n") catch return error.Invalid;
    return o.toOwnedSlice(a) catch error.Invalid;
}


fn jsonEqual(a: std.mem.Allocator, x: std.json.Value, y: std.json.Value) bool {
    const sx = std.json.Stringify.valueAlloc(a, x, .{}) catch return false;
    const sy = std.json.Stringify.valueAlloc(a, y, .{}) catch return false;
    return std.mem.eql(u8, sx, sy);
}

// ---- test discovery (the cross-check of `check`) -------------------------------------------------------------

/// Whether `rel` (relative to a package root, '/'-separated) is a test file by mopm's convention: `tests/**/test_*.mojo` and
/// `src/**/tests/test_*.mojo`. A copy of mopm's rule (test_harness.isTestPath), used only to notice a test file the committed
/// graph does not know; the graph itself is always mopm's.
pub fn isTestPath(rel: []const u8) bool {
    var first: []const u8 = "";
    var parent: []const u8 = "";
    var base: []const u8 = "";
    var n: usize = 0;
    var it = std.mem.splitScalar(u8, rel, '/');
    while (it.next()) |p| {
        if (p.len == 0 or p[0] == '.') return false;
        if (n == 0) first = p;
        parent = base;
        base = p;
        n += 1;
    }
    if (n < 2) return false;
    if (!std.mem.startsWith(u8, base, "test_") or !std.mem.endsWith(u8, base, ".mojo")) return false;
    if (std.mem.eql(u8, first, "tests")) return true;
    return std.mem.eql(u8, first, "src") and std.mem.eql(u8, parent, "tests");
}

/// The `subdir` a graph's `toolchain` object names ("" when it is not an object, or names none as a string): what a graph kept for a subdir must say.
pub fn toolchainSubdir(toolchain: std.json.Value) []const u8 {
    if (toolchain != .object) return "";
    const v = toolchain.object.get("subdir") orelse return "";
    return if (v == .string) v.string else "";
}
