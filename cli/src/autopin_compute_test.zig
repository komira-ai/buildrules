//! `buildrules autopin compute` on repositories built in a temporary directory. The network is a fake that serves
//! fixed digests and counts its calls. Every test is named for the defect it catches.

const std = @import("std");
const compute = @import("autopin_compute.zig");
const fetch = @import("fetch.zig");
const kit = @import("testkit.zig");
const manifest = @import("autopin_manifest.zig");
const npm = @import("npm_cmd.zig");
const sets_mod = @import("autopin_sets.zig");
const table = @import("autopin_table.zig");
const t = std.testing;

const sri_a = "sha512-" ++ "A" ** 86 ++ "==";
const sri_b = "sha512-" ++ "B" ** 85 ++ "A==";
const sha_a = "a" ** 64;
const reg = "https://registry.npmjs.org/";
const head = "3" ** 40;
const base = "4" ** 40;

var fetches: usize = 0;
var served_sri: []const u8 = sri_a;
var served_size: u64 = 11;

fn fake(a: std.mem.Allocator, url: []const u8) anyerror!fetch.Digest.Result {
    _ = a;
    _ = url;
    fetches += 1;
    return .{ .sha256 = sha_a, .sri512 = served_sri, .size = served_size };
}

fn reset() void {
    fetches = 0;
    served_sri = sri_a;
    served_size = 11;
    compute.fetcher = &fake;
    npm.fetcher = &fake;
}

const Pkg = struct { name: []const u8, version: []const u8 };

fn lockJson(a: std.mem.Allocator, pkgs: []const Pkg, extra: []const u8) ![]u8 {
    var out = std.ArrayList(u8).empty;
    try out.appendSlice(a, "{\"name\":\"demo\",\"lockfileVersion\":3,\"packages\":{\"\":{\"name\":\"demo\"}");
    for (pkgs) |p| {
        const base_name = if (std.mem.lastIndexOfScalar(u8, p.name, '/')) |i| p.name[i + 1 ..] else p.name;
        try out.print(a, ",\"node_modules/{s}\":{{\"version\":\"{s}\",\"resolved\":\"{s}{s}/-/{s}-{s}.tgz\",\"integrity\":\"{s}\"}}", .{ p.name, p.version, reg, p.name, base_name, p.version, sri_a });
    }
    try out.appendSlice(a, extra);
    try out.appendSlice(a, "}}");
    return out.items;
}

const two_pkgs = [_]Pkg{ .{ .name = "left-pad", .version = "1.3.0" }, .{ .name = "@scope/pkg", .version = "2.0.0" } };
const three_pkgs = [_]Pkg{ .{ .name = "left-pad", .version = "1.3.0" }, .{ .name = "@scope/pkg", .version = "2.0.0" }, .{ .name = "is-odd", .version = "3.0.1" } };

const pj = "{\"name\":\"demo\",\"version\":\"1.0.0\",\"scripts\":{\"test\":\"jest\"}}";
const pins_hdr = "# GENERATED by kpin. Do not edit by hand; regenerate with:\n#   ./buck2 run buildrules//rules/kpin -- lock\n\nKPIN_LOCK_VERSION = 1\n\nPINS = {}\n\n";

/// `dir` holds package.json, package-lock.json and the table the lock calls for, as `npm sync` leaves them.
fn syncedBuildrules(h: *kit.Harness, dir: []const u8, pkgs: []const Pkg) !void {
    try h.put(".buckconfig", "[cells]\n");
    try h.put(try std.fmt.allocPrint(h.a(), "{s}/package.json", .{dir}), pj);
    try h.put(try std.fmt.allocPrint(h.a(), "{s}/package-lock.json", .{dir}), try lockJson(h.a(), pkgs, ""));
    const r = h.run(&.{ "npm", "sync", dir });
    try t.expectEqual(@as(u8, 0), r.code);
}

fn syncedPins(h: *kit.Harness, dir: []const u8, pkgs: []const Pkg) !void {
    try h.put(".buckconfig", "[cells]\n");
    try h.put(try std.fmt.allocPrint(h.a(), "{s}/package.json", .{dir}), pj);
    try h.put(try std.fmt.allocPrint(h.a(), "{s}/package-lock.json", .{dir}), try lockJson(h.a(), pkgs, ""));
    try h.put(try std.fmt.allocPrint(h.a(), "{s}/pins.lock.bzl", .{dir}), try pinsTable(h.a(), pkgs));
}

fn pinsTable(a: std.mem.Allocator, pkgs: []const Pkg) ![]u8 {
    const sorted = try a.dupe(Pkg, pkgs);
    std.mem.sort(Pkg, sorted, {}, struct {
        fn less(_: void, x: Pkg, y: Pkg) bool {
            return std.mem.lessThan(u8, x.name, y.name);
        }
    }.less);
    var rows = std.ArrayList(table.Row).empty;
    for (sorted) |p| {
        const base_name = if (std.mem.lastIndexOfScalar(u8, p.name, '/')) |i| p.name[i + 1 ..] else p.name;
        try rows.append(a, .{
            .key = try std.fmt.allocPrint(a, "{s}@{s}", .{ p.name, p.version }),
            .name = p.name,
            .version = p.version,
            .url = try std.fmt.allocPrint(a, "{s}{s}/-/{s}-{s}.tgz", .{ reg, p.name, base_name, p.version }),
            .sri512 = sri_a,
            .sha256 = sha_a,
            .size = 11,
        });
    }
    // sorted by key, not by name: keys are name@version, which sorts like names here
    return table.freshPins(a, pins_hdr, rows.items);
}

fn event(h: *kit.Harness) !void {
    try h.put("event.json", "{\"action\":\"synchronize\",\"pull_request\":{\"number\":7,\"head\":{\"sha\":\"" ++ head ++ "\"},\"base\":{\"sha\":\"" ++ base ++ "\"}}}");
}

fn runCompute(h: *kit.Harness, out: []const u8, sets: []const []const u8) kit.Run {
    var argv = std.ArrayList([]const u8).empty;
    argv.appendSlice(h.a(), &.{ "autopin", "compute", "--event", "event.json", "--out", out }) catch unreachable;
    for (sets) |s| argv.appendSlice(h.a(), &.{ "--set", s }) catch unreachable;
    return h.run(argv.items);
}

fn readManifest(h: *kit.Harness, out: []const u8, sets: []const []const u8) !manifest.Manifest {
    const s = try sets_mod.Sets.parse(h.a(), sets);
    return manifest.parse(h.a(), h.read(try std.fmt.allocPrint(h.a(), "{s}/manifest.json", .{out})), s);
}

test "compute: a lock bump gives the regenerated table and a manifest for the pull request, fetching only the new package" {
    reset();
    const h = try kit.Harness.create();
    defer h.destroy();
    try syncedBuildrules(h, "site", &two_pkgs);
    try event(h);
    try h.put("site/package-lock.json", try lockJson(h.a(), &three_pkgs, ""));
    fetches = 0;
    const r = runCompute(h, "artifact", &.{"site=buildrules-lock"});
    try t.expectEqual(@as(u8, 0), r.code);
    try t.expectEqual(@as(usize, 1), fetches);
    const m = try readManifest(h, "artifact", &.{"site=buildrules-lock"});
    try t.expectEqual(@as(u64, 7), m.pr);
    try t.expectEqualStrings(head, m.head_sha);
    try t.expectEqualStrings(base, m.base_sha);
    try t.expectEqual(@as(usize, 1), m.files.len);
    try t.expectEqualStrings("site/buildrules.lock.bzl", m.files[0].path);
    const written = h.read("artifact/site/buildrules.lock.bzl");
    try t.expectEqualStrings(try @import("ctx.zig").sha256Hex(h.a(), written), m.files[0].sha256);
    try t.expect(kit.contains(written, "\"is-odd@3.0.1\": {"));
    try t.expect(kit.contains(written, "\"left-pad@1.3.0\": {"));
    try t.expect(kit.contains(r.out, "pinned is-odd@3.0.1"));
    // The repository itself is not touched: only --out is written.
    try t.expect(!kit.contains(h.read("site/buildrules.lock.bzl"), "is-odd"));
}

test "compute: nothing to do gives an empty file list and no table, and a rerun on the committed result changes nothing" {
    reset();
    const h = try kit.Harness.create();
    defer h.destroy();
    try syncedBuildrules(h, "site", &two_pkgs);
    try event(h);
    fetches = 0;
    var r = runCompute(h, "artifact", &.{"site=buildrules-lock"});
    try t.expectEqual(@as(u8, 0), r.code);
    try t.expectEqual(@as(usize, 0), fetches);
    try t.expectEqual(@as(usize, 0), (try readManifest(h, "artifact", &.{"site=buildrules-lock"})).files.len);
    try t.expect(!h.has("artifact/site/buildrules.lock.bzl"));
    try t.expect(kit.contains(r.out, "site: in sync"));
    // Bump, compute, commit the result by hand, compute again: zero diff.
    try h.put("site/package-lock.json", try lockJson(h.a(), &three_pkgs, ""));
    r = runCompute(h, "artifact2", &.{"site=buildrules-lock"});
    try t.expectEqual(@as(u8, 0), r.code);
    try h.put("site/buildrules.lock.bzl", h.read("artifact2/site/buildrules.lock.bzl"));
    fetches = 0;
    r = runCompute(h, "artifact3", &.{"site=buildrules-lock"});
    try t.expectEqual(@as(u8, 0), r.code);
    try t.expectEqual(@as(usize, 0), fetches);
    try t.expectEqual(@as(usize, 0), (try readManifest(h, "artifact3", &.{"site=buildrules-lock"})).files.len);
    try t.expect(!h.has("artifact3/site/buildrules.lock.bzl"));
}

