    try event(h2);
    try h2.put("infra/package-lock.json", swapped);
    const r2 = runCompute(h2, "artifact", &.{"infra=pins-lock"});
    try t.expectEqual(@as(u8, 1), r2.code);
    try t.expect(kit.contains(r2.err, "other bytes"));
    try t.expect(!h2.has("artifact/manifest.json"));
}

