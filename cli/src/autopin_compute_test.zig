test "compute: a hostile lock is refused before any download (alias, other host, git, bundled)" {
    const hostile = [_][]const u8{
        ",\"node_modules/x\":{\"name\":\"y\",\"version\":\"1.0.0\",\"resolved\":\"https://registry.npmjs.org/y/-/y-1.0.0.tgz\",\"integrity\":\"" ++ sri_a ++ "\"}",
        ",\"node_modules/x\":{\"version\":\"1.0.0\",\"resolved\":\"https://evil.example/x/-/x-1.0.0.tgz\",\"integrity\":\"" ++ sri_a ++ "\"}",
        ",\"node_modules/x\":{\"version\":\"1.0.0\",\"resolved\":\"git+ssh://git@github.com/o/x.git#abc\"}",
        ",\"node_modules/x\":{\"version\":\"1.0.0\",\"inBundle\":true}",
    };
    for (hostile) |extra| {
        reset();
        const h = try kit.Harness.create();
        defer h.destroy();
        try syncedBuildrules(h, "site", &two_pkgs);
        try syncedPins(h, "infra", &two_pkgs);
        try event(h);
        try h.put("site/package-lock.json", try lockJson(h.a(), &two_pkgs, extra));
        try h.put("infra/package-lock.json", try lockJson(h.a(), &two_pkgs, extra));
        fetches = 0;
        var r = runCompute(h, "artifact", &.{"site=buildrules-lock"});
        try t.expectEqual(@as(u8, 1), r.code);
        r = runCompute(h, "artifact2", &.{"infra=pins-lock"});
        try t.expectEqual(@as(u8, 1), r.code);
        try t.expectEqual(@as(usize, 0), fetches);
        try t.expect(!h.has("artifact/manifest.json"));
        try t.expect(!h.has("artifact2/manifest.json"));
    }
}

test "compute: downloads are capped: only the registry is fetched from" {
    reset();
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    compute.resetCounters();
    try t.expectError(error.HostNotAllowed, compute.capped(a, "https://evil.example/x.tgz"));
    try t.expectError(error.HostNotAllowed, compute.capped(a, "http://registry.npmjs.org/x.tgz"));
    try t.expectEqual(@as(usize, 0), fetches);
}

test "compute: downloads are capped: 64 MiB for one tarball" {
    reset();
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    compute.resetCounters();
    served_size = table.max_size + 1;
    try t.expectError(error.TarballTooLarge, compute.capped(a, reg ++ "x/-/x-1.0.0.tgz"));
    served_size = table.max_size;
    _ = try compute.capped(a, reg ++ "x/-/x-1.0.0.tgz");
}

test "compute: downloads are capped: 512 MiB together" {
    reset();
    var ar = std.heap.ArenaAllocator.init(t.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    compute.resetCounters();
    // Eight tarballs of 64 MiB fit, the ninth does not.
    served_size = table.max_size;
    var i: usize = 0;
    while (i < 8) : (i += 1) _ = try compute.capped(a, reg ++ "x/-/x-1.0.0.tgz");
    try t.expectError(error.TotalTooLarge, compute.capped(a, reg ++ "x/-/x-1.0.0.tgz"));
}

