//! The mopm versions a repository pins itself, in buildrules-pins.toml beside the Rust ones (pins_toml.zig):
//!
//!     [mopm."0.0.2"]
//!     url = "https://example.org/releases/mopm-0.0.2-linux-x86_64.tar.gz"
//!     sha256 = "<64 lower-case hex>"
//!     size = 977850                      # bytes of the tarball
//!
//! The tarball holds one directory named like the file without `.tar.gz`, and `mopm` in it. `render` turns the tables into
//! toolchains/mopm_pins.bzl, which `mopm_toolchains(extra = ...)` reads. A pin is a review item, which is why it is copied
//! into a committed file and not read at build time. A version rules/mopm/pins.bzl already pins is refused by the rules.

const std = @import("std");
const valid = @import("valid.zig");
const toolchain = @import("toolchain.zig");
const Diag = @import("diag.zig").Diag;

const Row = struct { version: []const u8, url: ?[]const u8 = null, sha256: ?[]const u8 = null, size: ?u64 = null };

pub const header = "# Generated by `buildrules mojo sync` from buildrules-pins.toml. Do not edit.\n" ++
    "# The mopm versions this repository pins itself, beyond rules/mopm/pins.bzl (docs/contract.md, section 12).\n";

pub const empty = header ++ "EXTRA_MOPM_VERSIONS = {}\n";

fn unquote(s: []const u8) ?[]const u8 {
    if (s.len < 2 or s[0] != '"' or s[s.len - 1] != '"') return null;
    const in = s[1 .. s.len - 1];
    if (std.mem.indexOfScalar(u8, in, '"') != null or std.mem.indexOfScalar(u8, in, '\\') != null) return null;
    return in;
}

fn bare(line: []const u8) []const u8 {
    var in_q = false;
    var end = line.len;
    for (line, 0..) |c, i| {
        if (c == '"') in_q = !in_q;
        if (c == '#' and !in_q) {
            end = i;
            break;
        }
    }
    return std.mem.trim(u8, line[0..end], " \t\r");
}

/// The file name of a tarball URL without `.tar.gz`, the directory it unpacks into.
pub fn unpackDir(url: []const u8) ?[]const u8 {
    const slash = std.mem.lastIndexOfScalar(u8, url, '/') orelse return null;
    const f = url[slash + 1 ..];
    if (!std.mem.endsWith(u8, f, ".tar.gz") or f.len <= ".tar.gz".len) return null;
    return f[0 .. f.len - ".tar.gz".len];
}

pub fn render(a: std.mem.Allocator, text: []const u8, diag: *Diag) error{Invalid}![]const u8 {
    const before = diag.count();
    var rows = std.ArrayList(Row).empty;
    var cur: ?usize = null;
    var skipping = false;
    var line_no: usize = 0;
    var it = std.mem.splitScalar(u8, text, '\n');
    while (it.next()) |raw| {
        line_no += 1;
        const line = bare(raw);
        if (line.len == 0) continue;
        if (line[0] == '[') {
            cur = null;
            skipping = false;
            if (line[line.len - 1] != ']') continue; // pins_toml.zig reports an unterminated header
            const inner = line[1 .. line.len - 1];
            const pre = "mopm.\"";
            if (!std.mem.startsWith(u8, inner, pre)) {
                skipping = true; // a [rust...] table: pins_toml.zig's
                continue;
            }
            const q = std.mem.indexOfScalarPos(u8, inner, pre.len, '"') orelse {
                diag.add("buildrules-pins.toml:{d}: the version in [{s}] is not quoted", .{ line_no, inner });
                continue;
            };
            const ver = inner[pre.len..q];
            if (q + 1 != inner.len) {
                diag.add("buildrules-pins.toml:{d}: [{s}]: a mopm table has no sub-tables", .{ line_no, inner });
                continue;
            }
            if (!toolchain.isExactRelease(ver)) {
                diag.add("buildrules-pins.toml:{d}: mopm \"{s}\" is not an exact release N.N.N", .{ line_no, ver });
                continue;
            }
            for (rows.items) |r| {
                if (std.mem.eql(u8, r.version, ver)) {
                    diag.add("buildrules-pins.toml:{d}: [mopm.\"{s}\"] appears twice", .{ line_no, ver });
                }
            }
            rows.append(a, .{ .version = ver }) catch return error.Invalid;
            cur = rows.items.len - 1;
            continue;
        }
        if (skipping) continue;
        const ri = cur orelse {
            diag.add("buildrules-pins.toml:{d}: `{s}` is outside any table", .{ line_no, line });
            continue;
        };
        const eq = std.mem.indexOfScalar(u8, line, '=') orelse {
            diag.add("buildrules-pins.toml:{d}: not `key = value`: {s}", .{ line_no, line });
            continue;
        };
        const key = std.mem.trim(u8, line[0..eq], " \t");
        const val = std.mem.trim(u8, line[eq + 1 ..], " \t");
        if (std.mem.eql(u8, key, "url")) {
            const v = unquote(val) orelse "";
            if (!valid.isUrl(v) or unpackDir(v) == null) diag.add("buildrules-pins.toml:{d}: url must be a quoted https URL of a .tar.gz", .{line_no});
            rows.items[ri].url = v;
        } else if (std.mem.eql(u8, key, "sha256")) {
            const v = unquote(val) orelse "";
            if (!valid.isSha256(v)) diag.add("buildrules-pins.toml:{d}: sha256 must be 64 lower-case hex digits in quotes", .{line_no});
            rows.items[ri].sha256 = v;
        } else if (std.mem.eql(u8, key, "size")) {
            const n = std.fmt.parseInt(u64, val, 10) catch 0;
            if (n == 0) diag.add("buildrules-pins.toml:{d}: size must be the tarball's length in bytes (a positive integer)", .{line_no});
            rows.items[ri].size = n;
        } else {
            diag.add("buildrules-pins.toml:{d}: unknown key `{s}` in a mopm table (url, sha256, size)", .{ line_no, key });
        }
    }
    for (rows.items) |r| {
        if (r.url == null or r.sha256 == null or r.size == null or r.size.? == 0) {
            diag.add("buildrules-pins.toml: mopm \"{s}\" needs url, sha256 and size", .{r.version});
        }
    }
    if (diag.count() != before) return error.Invalid;
    std.mem.sort(Row, rows.items, {}, struct {
        fn lt(_: void, x: Row, y: Row) bool {
            return std.mem.lessThan(u8, x.version, y.version);
        }
    }.lt);
    var o = std.ArrayList(u8).empty;
    o.appendSlice(a, header) catch return error.Invalid;
    if (rows.items.len == 0) {
        o.appendSlice(a, "EXTRA_MOPM_VERSIONS = {}\n") catch return error.Invalid;
        return o.toOwnedSlice(a) catch error.Invalid;
    }
    o.appendSlice(a, "EXTRA_MOPM_VERSIONS = {\n") catch return error.Invalid;
    for (rows.items) |r| {
        o.print(a, "    \"{s}\": {{\n        \"url\": \"{s}\",\n        \"sha256\": \"{s}\",\n        \"size\": {d},\n        \"dir\": \"{s}\",\n    }},\n", .{ r.version, r.url.?, r.sha256.?, r.size.?, unpackDir(r.url.?).? }) catch return error.Invalid;
    }
    o.appendSlice(a, "}\n") catch return error.Invalid;
    return o.toOwnedSlice(a) catch error.Invalid;
}
